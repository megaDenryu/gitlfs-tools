//! 設定の探索・解析・解決全体で使うエラー分類。
//!
//! 「エラー分類」役割のファイルである（コード分割規約.md 1節）。認証情報を混入させない
//! （CLAUDE.md）ため、各バリアントは設定ファイルの全量・トークン・PC固有の絶対パスを
//! 持たない。`toml`crateの`Display`は解析に失敗した行の内容を再掲するため使わず、
//! 内容を含まない`message()`だけを`解析失敗`へ格納する。

use gitlfs_tools_domain::プロファイル名;

/// プロジェクト設定・PC設定の探索・解析・解決で起こりうる失敗の分類。
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum 設定エラー {
    #[error("プロジェクト設定ファイル(.large-assets.toml)が見つかりません。Git作業ツリーのルートに配置されているか確認してください")]
    プロジェクト設定未検出,

    #[error("PC設定ファイルが見つかりません。導入手順に従ってPC設定を作成してください")]
    PC設定未検出,

    #[error("この環境の標準設定ディレクトリを特定できませんでした")]
    PC設定ディレクトリ不明,

    #[error("設定ファイルの解析に失敗しました: {説明}")]
    解析失敗 { 説明: String },

    #[error("スキーマ版が対応していません(受信した版: {受信した版}, 受理できる版: {受理できる版})")]
    未対応スキーマ版 { 受信した版: u64, 受理できる版: u64 },

    #[error("論理プロファイル'{}'がPC設定に定義されていません", プロファイル名.文字列表現())]
    未定義プロファイル { プロファイル名: プロファイル名 },

    #[error("設定ファイルの読み込みに失敗しました: {説明}")]
    ローカル入出力 { 説明: String },

    #[error("未対応の保管先の種類です(受信した値: {受信した値}, 受理できる値: {受理できる値})")]
    未対応の保管先の種類 { 受信した値: String, 受理できる値: String },

    #[error("PC設定のプロファイルに必要なキーがありません: {キー名}")]
    プロファイルの必須キー不足 { キー名: String },

    #[error("storage = \"{保管先の種類}\"では使わないキーが指定されています: {キー名}。削除してください")]
    この保管先の種類では使わないキー { キー名: String, 保管先の種類: String },
}
