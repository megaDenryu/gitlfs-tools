//! `error.code`の数値割り当て。Git LFS custom transfer protocolは`error.code`の値域を
//! 定めていない（参照: lfs-custom-transfer-protocol.md 10節）ため、本リポジトリの割り当てを
//! ここへ固定し、README.mdの対応表と一致させる（Issue #2 10節「数値codeの対応表を実装と
//! READMEで固定する」）。
//!
//! 各バリアントは`初期化エラー`・`保管エラー`・`整合性エラー`・`プロトコル解析エラー`の
//! いずれかの枝に1対1で対応する（`presentable_error.rs`参照）。分類を足したときに
//! 網羅性の欠落へコンパイルエラーで気づけるよう、既定値へ落とす変換をしない。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum エラーコード {
    プロジェクト設定未検出,
    PC設定未検出,
    PC設定ディレクトリ不明,
    設定解析失敗,
    未対応スキーマ版,
    未定義プロファイル,
    設定読み込み入出力失敗,
    Rclone実行ファイル不在,
    保管設定不備,
    認証接続失敗,
    オブジェクト未存在,
    不正な識別子形式,
    バイト数の不一致,
    内容ハッシュの不一致,
    ローカル入出力失敗,
    Rcloneプロセス実行失敗,
    JSON解析失敗,
    未知のevent,
    必須フィールド欠落または不正,
}

impl エラーコード {
    pub fn 値(self) -> u32 {
        match self {
            Self::プロジェクト設定未検出 => 1,
            Self::PC設定未検出 => 2,
            Self::PC設定ディレクトリ不明 => 3,
            Self::設定解析失敗 => 4,
            Self::未対応スキーマ版 => 5,
            Self::未定義プロファイル => 6,
            Self::設定読み込み入出力失敗 => 7,
            Self::Rclone実行ファイル不在 => 8,
            Self::保管設定不備 => 9,
            Self::認証接続失敗 => 10,
            Self::オブジェクト未存在 => 11,
            Self::不正な識別子形式 => 12,
            Self::バイト数の不一致 => 13,
            Self::内容ハッシュの不一致 => 14,
            Self::ローカル入出力失敗 => 15,
            Self::Rcloneプロセス実行失敗 => 16,
            Self::JSON解析失敗 => 17,
            Self::未知のevent => 18,
            Self::必須フィールド欠落または不正 => 19,
        }
    }
}
