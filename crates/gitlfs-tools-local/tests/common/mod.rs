//! ローカルディレクトリ保管庫の結合テスト共通のフィクスチャ補助関数。
//!
//! 注意: `tests/`配下の各テストファイルは個別の結合テストバイナリとしてコンパイルされ、
//! このモジュールを毎回別々にコンパイルする。どのバイナリも補助関数の全部は使わないため
//! `dead_code`警告が出るが、これは共有テストヘルパーの既知の性質である。

#![allow(dead_code)]

use std::io::Write;
use std::path::{Path, PathBuf};

use gitlfs_tools_domain::{オブジェクト識別子, 保管先基底パス, 期待バイト数, 検証前のローカルファイル, 検証済みローカルファイル};
use gitlfs_tools_local::{ローカルディレクトリ保管庫, ローカル保管先ルートディレクトリ};
use sha2::{Digest, Sha256};

/// 一時ディレクトリを保管先の基点とする保管庫を作る。実ユーザーの保管先へは触れない。
pub fn 保管庫を作る(ルート: &Path) -> Result<ローカルディレクトリ保管庫, Box<dyn std::error::Error>> {
    Ok(ローカルディレクトリ保管庫::生成する(
        ローカル保管先ルートディレクトリ::生成する(ルート),
        保管先基底パス::生成する(基底パス文字列にする(ルート)?)?,
    ))
}

/// 保管先の基点をdomain層が扱う`/`区切りの文字列にする。
pub fn 基底パス文字列にする(ルート: &Path) -> Result<String, Box<dyn std::error::Error>> {
    Ok(ルート.to_str().ok_or("パスがUTF-8ではありません")?.replace('\\', "/"))
}

/// 指定した内容のファイルを作り、その識別子と検証済みローカルファイルを返す。
pub fn 内容を書いた検証済みローカルファイルを作る(
    内容: &[u8],
) -> Result<(tempfile::NamedTempFile, オブジェクト識別子, 検証済みローカルファイル), Box<dyn std::error::Error>> {
    let mut ファイル = tempfile::NamedTempFile::new()?;
    ファイル.write_all(内容)?;

    let 識別子 = 内容から識別子を求める(内容)?;
    let バイト数 = 期待バイト数::生成する(u64::try_from(内容.len())?);
    let 検証済み = 検証前のローカルファイル::生成する(ファイル.path()).検証する(&識別子, バイト数)?;

    Ok((ファイル, 識別子, 検証済み))
}

pub fn 内容から識別子を求める(内容: &[u8]) -> Result<オブジェクト識別子, Box<dyn std::error::Error>> {
    let ダイジェスト = Sha256::digest(内容);
    let 十六進文字列: String = ダイジェスト.iter().map(|バイト| format!("{バイト:02x}")).collect();
    Ok(オブジェクト識別子::生成する(&十六進文字列)?)
}

/// 保管先の基点から見た最終オブジェクトの配置先。実装と同じ綴りをテスト側で独立に組み立て、
/// 期待どおりの位置へ落ちていることを確かめる。
pub fn 最終オブジェクトのパス(ルート: &Path, 識別子: &オブジェクト識別子) -> PathBuf {
    let 文字列 = 識別子.文字列表現();
    ルート.join("lfs").join("objects").join("sha256").join(&文字列[0..2]).join(&文字列[2..4]).join(文字列)
}

/// 保管先の一時アップロード領域。転送後に何も残っていないことの確認に使う。
pub fn 一時アップロード領域のパス(ルート: &Path) -> PathBuf {
    ルート.join("lfs").join("tmp")
}
