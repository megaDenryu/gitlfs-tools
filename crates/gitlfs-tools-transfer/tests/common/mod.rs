//! テスト専用の偽`オブジェクト保管庫`とその補助関数。
//!
//! rcloneを起動せずに`資産転送サービス`のユースケースを検証するための実装であり、
//! 本体クレートには含めない（Issue #6テスト節「偽の保管庫は本体のコードではなくテスト側に
//! 置く」）。
//!
//! 注意: `tests/`配下の各テストファイルは個別の結合テストバイナリとしてコンパイルされ、
//! このモジュールを毎回別々にコンパイルする。どのバイナリも補助関数の全部は使わないため
//! `dead_code`警告が出る。これは共有テストヘルパーの既知の性質であり、本体クレートの
//! lint（`unwrap_used`等のdeny）を緩和するものではない。

#![allow(dead_code)]

use std::cell::RefCell;
use std::collections::HashMap;
use std::path::Path;

use gitlfs_tools_domain::{オブジェクト状態, オブジェクト識別子, 一時ファイルパス, 保管エラー, 期待バイト数, 検証済みローカルファイル};
use gitlfs_tools_storage_port::{アップロード結果, オブジェクト保管庫, 保管オブジェクト総数};
use sha2::{Digest, Sha256};

/// 内容からSHA-256の16進文字列を計算する。テストが正しいオブジェクト識別子を組み立てる
/// ために使う。
pub fn sha256の16進文字列(内容: &[u8]) -> String {
    let ダイジェスト = Sha256::digest(内容);
    ダイジェスト.iter().map(|バイト| format!("{バイト:02x}")).collect()
}

/// 指定ディレクトリの下へ内容を書いたファイルを作り、そのパスを返す。
pub fn 内容を書いたファイルを作る(ディレクトリ: &Path, ファイル名: &str, 内容: &[u8]) -> std::io::Result<std::path::PathBuf> {
    let パス = ディレクトリ.join(ファイル名);
    std::fs::write(&パス, 内容)?;
    Ok(パス)
}

/// 保管先に置かれたオブジェクトの状態だけを覚える偽の保管庫。
///
/// 呼び出し回数を`RefCell`で記録し、`Rc`で包んで共有することでテスト側からも
/// `資産転送サービス`へ移した後の呼び出し回数を確認できる。
pub struct 偽の保管庫 {
    保存済みバイト数: RefCell<HashMap<String, u64>>,
    アップロード呼び出し回数: RefCell<HashMap<String, u32>>,
    ダウンロード時に返す内容: RefCell<HashMap<String, Vec<u8>>>,
}

impl 偽の保管庫 {
    pub fn 生成する() -> Self {
        Self {
            保存済みバイト数: RefCell::new(HashMap::new()),
            アップロード呼び出し回数: RefCell::new(HashMap::new()),
            ダウンロード時に返す内容: RefCell::new(HashMap::new()),
        }
    }

    /// 保管先に既にオブジェクトが存在する状態を作る（ダウンロードの前提条件を作るため）。
    pub fn 存在するオブジェクトとして登録する(&self, 識別子文字列: &str, バイト数: u64) {
        self.保存済みバイト数.borrow_mut().insert(識別子文字列.to_owned(), バイト数);
    }

    /// ダウンロード時に返す内容を登録する。登録したバイト列がそのまま一時ファイルへ
    /// 書き込まれるため、破損ダウンロードを意図的に再現できる。
    pub fn ダウンロード時の内容を登録する(&self, 識別子文字列: &str, 内容: Vec<u8>) {
        self.ダウンロード時に返す内容.borrow_mut().insert(識別子文字列.to_owned(), 内容);
    }

    pub fn アップロード呼び出し回数(&self, 識別子文字列: &str) -> u32 {
        *self.アップロード呼び出し回数.borrow().get(識別子文字列).unwrap_or(&0)
    }
}

impl オブジェクト保管庫 for 偽の保管庫 {
    fn 存在を確認する(&self, 識別子: &オブジェクト識別子, 期待バイト数: 期待バイト数) -> Result<オブジェクト状態, 保管エラー> {
        match self.保存済みバイト数.borrow().get(識別子.文字列表現()) {
            None => Ok(オブジェクト状態::未存在),
            Some(&実バイト数) if 実バイト数 == 期待バイト数.値() => Ok(オブジェクト状態::存在),
            Some(&実バイト数) => Ok(オブジェクト状態::サイズの不一致 {
                実サイズ: 期待バイト数::生成する(実バイト数),
            }),
        }
    }

    fn 保管しているオブジェクトの総数を数える(&self) -> Result<保管オブジェクト総数, 保管エラー> {
        let 件数 = u64::try_from(self.保存済みバイト数.borrow().len()).unwrap_or(u64::MAX);
        Ok(保管オブジェクト総数::生成する(件数))
    }

    fn アップロードする(&self, 識別子: &オブジェクト識別子, 転送元: &検証済みローカルファイル) -> Result<アップロード結果, 保管エラー> {
        *self
            .アップロード呼び出し回数
            .borrow_mut()
            .entry(識別子.文字列表現().to_owned())
            .or_insert(0) += 1;
        self.保存済みバイト数
            .borrow_mut()
            .insert(識別子.文字列表現().to_owned(), 転送元.バイト数().値());
        Ok(アップロード結果::転送済み)
    }

    fn ダウンロードする(&self, 識別子: &オブジェクト識別子, _期待バイト数: 期待バイト数, 保存先: &一時ファイルパス) -> Result<(), 保管エラー> {
        let 内容 = self
            .ダウンロード時に返す内容
            .borrow()
            .get(識別子.文字列表現())
            .cloned()
            .unwrap_or_default();
        std::fs::write(保存先.パス(), 内容).map_err(|エラー| 保管エラー::ローカル入出力 {
            説明: format!("偽の保管庫の書き込みに失敗しました: {エラー}"),
        })
    }
}

/// `&偽の保管庫`をそのまま`オブジェクト保管庫`として使えるようにする委譲実装。
/// テストが所有権を手元に残しつつ（呼び出し回数を後から確認するため）、参照を
/// `資産転送サービス`へ渡すために必要（`Rc`は`fundamental`でなく孤児則を満たせないが、
/// 参照`&T`は`fundamental`であるためこの形なら実装できる）。
impl オブジェクト保管庫 for &偽の保管庫 {
    fn 存在を確認する(&self, 識別子: &オブジェクト識別子, 期待バイト数: 期待バイト数) -> Result<オブジェクト状態, 保管エラー> {
        (*self).存在を確認する(識別子, 期待バイト数)
    }

    fn 保管しているオブジェクトの総数を数える(&self) -> Result<保管オブジェクト総数, 保管エラー> {
        (*self).保管しているオブジェクトの総数を数える()
    }

    fn アップロードする(&self, 識別子: &オブジェクト識別子, 転送元: &検証済みローカルファイル) -> Result<アップロード結果, 保管エラー> {
        (*self).アップロードする(識別子, 転送元)
    }

    fn ダウンロードする(&self, 識別子: &オブジェクト識別子, 期待バイト数: 期待バイト数, 保存先: &一時ファイルパス) -> Result<(), 保管エラー> {
        (*self).ダウンロードする(識別子, 期待バイト数, 保存先)
    }
}
