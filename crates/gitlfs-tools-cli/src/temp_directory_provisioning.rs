//! `init`要求が求める「一時保存先を作成する」手続き。`一時ディレクトリ`はパスの生アクセサを
//! 公開しない値型のため、払い出し済みの一時ファイルパスから親ディレクトリを求めて作成する
//! （domain・rcloneクレートを触らずに済ませるための、コンポジションルート側の組み立て）。

use gitlfs_tools_domain::{一時ディレクトリ, 保管エラー};
use gitlfs_tools_protocol::初期化エラー;

pub(crate) fn 一時保存先を作成する(一時ディレクトリ: &一時ディレクトリ) -> Result<(), 初期化エラー> {
    let サンプルパス = 一時ディレクトリ.固有の一時ファイルパスを払い出す();
    let Some(親ディレクトリ) = サンプルパス.パス().parent() else { return Ok(()) };

    std::fs::create_dir_all(親ディレクトリ).map_err(|エラー| {
        初期化エラー::保管失敗(保管エラー::ローカル入出力 {
            説明: format!("一時保存先の作成に失敗しました: {エラー}"),
        })
    })
}
