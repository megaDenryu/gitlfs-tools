//! `init`要求の処理手続き（設定読み込み・プロファイル解決・rclone起動確認・一時保存先の
//! 作成・資産転送サービスの組み立て）を抽象化する境界。実装は`lfs-rclone-cli`が持つ
//! （アーキテクチャ.md 判断2「プロトコルアダプタは保管庫の実装を知らない」）。開始する
//! 操作はコールバックでなく、この型のメソッドとして表す
//! （グローバルCLAUDE.md「サービスの依存保持とコールバックの限定」）。

use lfs_rclone_domain::保管エラー;
use lfs_rclone_transfer::{アップロード完了, アップロード要求, ダウンロード完了, ダウンロード要求};

use crate::init_error::初期化エラー;
use crate::transfer_operation_kind::転送操作種別;

/// `init`の手続きを実行し、以後のアップロード・ダウンロードを受け付けるセッションを開始する。
pub trait 転送セッション開始境界 {
    type 開始済みセッション: 開始済み転送セッション;

    fn 開始する(&self, 操作種別: 転送操作種別) -> Result<Self::開始済みセッション, 初期化エラー>;
}

/// `init`を終えたセッション。アップロード・ダウンロードの実行だけを提供する。
pub trait 開始済み転送セッション {
    fn アップロードする(&self, 要求: アップロード要求) -> Result<アップロード完了, 保管エラー>;

    fn ダウンロードする(&self, 要求: ダウンロード要求) -> Result<ダウンロード完了, 保管エラー>;
}
