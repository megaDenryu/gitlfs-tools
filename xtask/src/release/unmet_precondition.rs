//! タグを発行してよいかどうかの判断。gitが答えた事実を受け取り、満たしていない前提だけを集める。
//!
//! 3つの前提を確かめる。第1に、作業ツリーに未コミットの変更が無いことである。タグは
//! コミットを指すため、コミットしていない変更はタグの指す内容に入らない。第2に、現在の
//! ブランチがmainであることである。第3に、同じ名前のタグがまだ無いことである。既にある
//! タグを作り直すと、そのタグを起点に作られたReleaseとの対応が崩れる。

use crate::release::git_work_tree::Git作業ツリー;
use crate::release::release_tag::リリースタグ名;

const 発行してよいブランチ名: &str = "main";

/// 発行の前提のうち、現在の状態が満たしていないもの。空であれば発行してよい。
pub struct 満たしていないリリースの前提(Vec<String>);

impl 満たしていないリリースの前提 {
    pub fn 作業ツリーとタグ名から調べる(作業ツリー: &Git作業ツリー, タグ名: &リリースタグ名) -> Result<Self, String> {
        let mut 一覧 = Vec::new();

        if 作業ツリー.未コミットの変更が残っているか()? {
            一覧.push("作業ツリーに未コミットの変更が残っている。コミットしてから発行する".to_owned());
        }

        let ブランチ名 = 作業ツリー.現在のブランチ名()?;
        if ブランチ名 != 発行してよいブランチ名 {
            一覧.push(format!("現在のブランチが{発行してよいブランチ名}ではない: {ブランチ名}"));
        }

        if 作業ツリー.同じ名前のタグが既にあるか(タグ名)? {
            一覧.push(format!(
                "同じ名前のタグが既にある: {}。Cargo.tomlの[workspace.package]のversionを上げる",
                タグ名.タグ名の文字列()
            ));
        }

        Ok(Self(一覧))
    }

    pub fn すべて満たしているか(&self) -> bool {
        self.0.is_empty()
    }

    pub fn 件数(&self) -> usize {
        self.0.len()
    }

    pub fn 説明一覧(&self) -> &[String] {
        &self.0
    }
}
