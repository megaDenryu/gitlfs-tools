//! `doctor`の追加診断4「保管先へ実際に書き込めるか」の中核となる確認手続き。一時オブジェクト
//! の領域（`<基底パス>/lfs/tmp/<UUID>`）だけを使い、書き込み・読み戻し・削除を行う。
//! 最終オブジェクトの領域（`lfs/objects/...`）へは書かない
//! （`保管先基底パス::オブジェクトパスを求める`を一度も呼ばないことで担保する）。

use std::path::Path;

use lfs_rclone_domain::{一時ディレクトリ, 保管エラー, 保管先オブジェクトパス, 保管先基底パス, Rcloneリモート名};

use crate::timeout_process_runner::タイムアウト付きrclone実行器;

const 確認用のペイロード: &[u8] = b"git-lfs-rclone-storage doctor probe\n";

/// 書き込みと読み戻し自体は成功したことを前提に、後片づけ（保管先の一時オブジェクトの
/// 削除）が残っているかどうかを表す。
pub(crate) enum 書き込み確認結果 {
    問題なし,
    片付け残り { 説明: String },
}

pub(crate) struct 保管先書き込み確認 {
    実行器: タイムアウト付きrclone実行器,
    リモート名: Rcloneリモート名,
}

impl 保管先書き込み確認 {
    pub(crate) fn 生成する(実行器: タイムアウト付きrclone実行器, リモート名: Rcloneリモート名) -> Self {
        Self { 実行器, リモート名 }
    }

    pub(crate) fn 一時オブジェクトで確認する(
        &self,
        基底パス: &保管先基底パス,
        ローカル一時ディレクトリ: &一時ディレクトリ,
    ) -> Result<書き込み確認結果, 保管エラー> {
        let 一時アップロード先 = 基底パス.一時アップロード先を払い出す();
        let 書き込み元 = ローカル一時ディレクトリ.固有の一時ファイルパスを払い出す();
        let 読み戻し先 = ローカル一時ディレクトリ.固有の一時ファイルパスを払い出す();

        let 確認結果 = self.書き込みと読み戻しを試みる(&一時アップロード先, 書き込み元.パス(), 読み戻し先.パス());
        let 片付け結果 = self.片付ける(&一時アップロード先, 書き込み元.パス(), 読み戻し先.パス());

        確認結果?;
        Ok(match 片付け結果 {
            Ok(()) => 書き込み確認結果::問題なし,
            Err(説明) => 書き込み確認結果::片付け残り { 説明 },
        })
    }

    fn 書き込みと読み戻しを試みる(
        &self,
        一時アップロード先: &保管先オブジェクトパス,
        書き込み元: &Path,
        読み戻し先: &Path,
    ) -> Result<(), 保管エラー> {
        if let Some(親) = 書き込み元.parent() {
            std::fs::create_dir_all(親).map_err(|エラー| 保管エラー::ローカル入出力 {
                説明: format!("確認用の一時ディレクトリを作成できませんでした: {エラー}"),
            })?;
        }
        std::fs::write(書き込み元, 確認用のペイロード)
            .map_err(|エラー| 保管エラー::ローカル入出力 { 説明: format!("確認用データの書き込みに失敗しました: {エラー}") })?;

        let 書き込み元文字列 = 書き込み元.to_string_lossy().into_owned();
        let 読み戻し先文字列 = 読み戻し先.to_string_lossy().into_owned();
        let 宛先 = self.リモートパス表現(一時アップロード先);

        self.実行器.実行する(&["copyto", "--ignore-times", "-q", "--stats", "0", 書き込み元文字列.as_str(), 宛先.as_str()])?;
        self.実行器.実行する(&["copyto", "--ignore-times", "-q", "--stats", "0", 宛先.as_str(), 読み戻し先文字列.as_str()])?;

        let 読み戻し内容 = std::fs::read(読み戻し先)
            .map_err(|エラー| 保管エラー::ローカル入出力 { 説明: format!("読み戻したデータを読み込めませんでした: {エラー}") })?;
        if 読み戻し内容 == 確認用のペイロード {
            Ok(())
        } else {
            Err(保管エラー::子プロセス { 説明: "読み戻した内容が書き込んだ内容と一致しません".to_owned() })
        }
    }

    fn 片付ける(&self, 一時アップロード先: &保管先オブジェクトパス, 書き込み元: &Path, 読み戻し先: &Path) -> Result<(), String> {
        let _ = std::fs::remove_file(書き込み元);
        let _ = std::fs::remove_file(読み戻し先);

        let 宛先 = self.リモートパス表現(一時アップロード先);
        self.実行器
            .実行する(&["deletefile", "-q", 宛先.as_str()])
            .map_err(|エラー| format!("保管先の一時オブジェクトを削除できませんでした: {エラー}"))
    }

    fn リモートパス表現(&self, パス: &保管先オブジェクトパス) -> String {
        format!("{}:{}", self.リモート名.文字列表現(), パス.文字列表現())
    }
}
