//! 保管先のオブジェクト在否の点検サービス（Issue #12）。Gitへの問い合わせも表示の組み立ても
//! 知らず、`オブジェクト保管庫`だけへ依存する。

use lfs_rclone_domain::{オブジェクト状態, 保管エラー};
use lfs_rclone_storage_port::オブジェクト保管庫;

use crate::audit_report::点検報告;
use crate::audit_target_object::点検対象オブジェクト;
use crate::missing_object::{欠落オブジェクト, 欠落の事由};

/// 与えられた点検対象が保管先に在るかを1件ずつ確かめ、欠落を集めるサービス。保管庫を依存として
/// コンストラクタで保持する（グローバルCLAUDE.md「サービスの依存保持とコールバックの限定」条1）。
///
/// 突き合わせは片方向である。「点検対象に在るものが保管先に在るか」だけを見て、保管先に在って
/// 点検対象に無いオブジェクトを違反として報告しない。保管先は複数のリポジトリで共用しており、
/// 他のリポジトリが置いたオブジェクトが在るのが正常な状態であるためである（Issue #12のコメントで
/// 確定した実装の必須条件）。
pub struct 保管先オブジェクト在否点検サービス<保管庫> {
    保管庫: 保管庫,
}

impl<保管庫: オブジェクト保管庫> 保管先オブジェクト在否点検サービス<保管庫> {
    pub fn 生成する(保管庫: 保管庫) -> Self {
        Self { 保管庫 }
    }

    /// 対象を順に確かめ、欠落を集めた報告を返す。保管先への問い合わせ自体が失敗した場合は、
    /// 欠落として数えず失敗を返す。問い合わせられなかったものを「在る」とも「無い」とも
    /// 報告しないためである。
    pub fn 点検する(&self, 対象一覧: &[点検対象オブジェクト]) -> Result<点検報告, 保管エラー> {
        let mut 欠落一覧 = Vec::new();

        for 対象 in 対象一覧 {
            match self.保管庫.存在を確認する(対象.識別子(), 対象.バイト数())? {
                オブジェクト状態::存在 => {}
                オブジェクト状態::未存在 => {
                    欠落一覧.push(欠落オブジェクト::生成する(対象.識別子().clone(), 欠落の事由::保管先に実体が無い));
                }
                オブジェクト状態::サイズの不一致 { 実サイズ } => {
                    欠落一覧.push(欠落オブジェクト::生成する(
                        対象.識別子().clone(),
                        欠落の事由::バイト数が食い違う { 保管先の実サイズ: 実サイズ },
                    ));
                }
            }
        }

        Ok(点検報告::生成する(対象一覧.len(), 欠落一覧))
    }
}
