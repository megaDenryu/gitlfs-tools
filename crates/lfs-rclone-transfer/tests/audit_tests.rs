//! `保管先オブジェクト在否点検サービス`が、欠けているオブジェクトだけを報告し、点検対象に
//! 無い保管先のオブジェクト（他のリポジトリが置いたもの）を違反として報告しないことを
//! 確かめる。

mod common;

use lfs_rclone_domain::{オブジェクト識別子, 期待バイト数};
use lfs_rclone_transfer::{保管先オブジェクト在否点検サービス, 欠落の事由, 点検対象オブジェクト};

fn 点検対象にする(内容: &[u8]) -> Result<点検対象オブジェクト, Box<dyn std::error::Error>> {
    let 識別子 = オブジェクト識別子::生成する(&common::sha256の16進文字列(内容))?;
    Ok(点検対象オブジェクト::生成する(識別子, 期待バイト数::生成する(u64::try_from(内容.len())?)))
}

#[test]
fn 全て在れば欠落なしとして点検件数を報告する() -> Result<(), Box<dyn std::error::Error>> {
    let 保管庫 = common::偽の保管庫::生成する();
    let 内容一覧: [&[u8]; 2] = [b"audit present one", b"audit present two"];
    for 内容 in 内容一覧 {
        保管庫.存在するオブジェクトとして登録する(&common::sha256の16進文字列(内容), u64::try_from(内容.len())?);
    }
    let 対象一覧 = 内容一覧.iter().map(|内容| 点検対象にする(内容)).collect::<Result<Vec<_>, _>>()?;

    let 報告 = 保管先オブジェクト在否点検サービス::生成する(&保管庫).点検する(&対象一覧)?;

    assert!(報告.全て保管先に在るか());
    assert_eq!(報告.点検した件数(), 2);
    Ok(())
}

#[test]
fn 実体が消えたオブジェクトを欠落として報告する() -> Result<(), Box<dyn std::error::Error>> {
    let 保管庫 = common::偽の保管庫::生成する();
    let 在る内容: &[u8] = b"audit remaining";
    let 消えた内容: &[u8] = b"audit deleted";
    保管庫.存在するオブジェクトとして登録する(&common::sha256の16進文字列(在る内容), u64::try_from(在る内容.len())?);
    let 対象一覧 = vec![点検対象にする(在る内容)?, 点検対象にする(消えた内容)?];

    let 報告 = 保管先オブジェクト在否点検サービス::生成する(&保管庫).点検する(&対象一覧)?;

    assert_eq!(報告.点検した件数(), 2);
    assert_eq!(報告.欠落一覧().len(), 1);
    let 欠落 = 報告.欠落一覧().first().ok_or("欠落が1件あるはずである")?;
    assert_eq!(欠落.識別子().文字列表現(), common::sha256の16進文字列(消えた内容));
    assert_eq!(欠落.事由(), 欠落の事由::保管先に実体が無い);
    Ok(())
}

#[test]
fn バイト数が食い違うオブジェクトを事由つきで報告する() -> Result<(), Box<dyn std::error::Error>> {
    let 保管庫 = common::偽の保管庫::生成する();
    let 内容: &[u8] = b"audit truncated";
    保管庫.存在するオブジェクトとして登録する(&common::sha256の16進文字列(内容), 3);

    let 報告 = 保管先オブジェクト在否点検サービス::生成する(&保管庫).点検する(&[点検対象にする(内容)?])?;

    let 欠落 = 報告.欠落一覧().first().ok_or("欠落が1件あるはずである")?;
    assert_eq!(欠落.事由(), 欠落の事由::バイト数が食い違う { 保管先の実サイズ: 期待バイト数::生成する(3) });
    Ok(())
}

#[test]
fn 点検対象に無い保管先のオブジェクトを違反として報告しない() -> Result<(), Box<dyn std::error::Error>> {
    let 保管庫 = common::偽の保管庫::生成する();
    let 自分の内容: &[u8] = b"audit mine";
    let 他のリポジトリの内容: &[u8] = b"audit belongs to another repository";
    保管庫.存在するオブジェクトとして登録する(&common::sha256の16進文字列(自分の内容), u64::try_from(自分の内容.len())?);
    保管庫.存在するオブジェクトとして登録する(
        &common::sha256の16進文字列(他のリポジトリの内容),
        u64::try_from(他のリポジトリの内容.len())?,
    );

    let 報告 = 保管先オブジェクト在否点検サービス::生成する(&保管庫).点検する(&[点検対象にする(自分の内容)?])?;

    assert!(報告.全て保管先に在るか(), "他のリポジトリが置いたオブジェクトを違反として報告してはならない");
    assert_eq!(報告.点検した件数(), 1);
    Ok(())
}
