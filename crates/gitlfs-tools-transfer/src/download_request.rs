//! ダウンロード要求を表す値型。

use gitlfs_tools_domain::{オブジェクト識別子, 整合性エラー, 期待バイト数};

/// ダウンロードの要求。要求には保存先パスを含まない。保存先はagentが管理する一時ファイルと
/// してサービス自身が払い出す（Issue #2 3.4節「要求には保存先pathが含まれない」）。
pub struct ダウンロード要求 {
    識別子: オブジェクト識別子,
    バイト数: 期待バイト数,
}

impl ダウンロード要求 {
    /// Git LFSから受け取る生の識別子文字列とバイト数から要求を組み立てる。
    /// 識別子が64文字の小文字16進文字列でなければ`整合性エラー`を返す。
    pub fn 生成する(識別子文字列: &str, バイト数: u64) -> Result<Self, 整合性エラー> {
        Ok(Self {
            識別子: オブジェクト識別子::生成する(識別子文字列)?,
            バイト数: 期待バイト数::生成する(バイト数),
        })
    }

    pub fn 識別子(&self) -> &オブジェクト識別子 {
        &self.識別子
    }

    pub fn バイト数(&self) -> 期待バイト数 {
        self.バイト数
    }
}
