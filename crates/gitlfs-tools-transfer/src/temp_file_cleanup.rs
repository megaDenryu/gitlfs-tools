//! ダウンロード失敗時に一時ファイルを可能な限り削除する外部境界。
//!
//! 役割は「外部境界」である（コード分割規約.md 1節）。`資産転送サービス`が失敗経路でだけ
//! 呼ぶ、ローカルファイルシステムへの直接操作をここへ閉じる。

use gitlfs_tools_domain::一時ファイルパス;

/// 一時ファイルを可能な限り削除する。
///
/// 注意: 削除自体が失敗しても呼び出し側へは伝えない。削除の失敗を元の転送失敗より優先して
/// 返すと「削除の失敗が元の失敗を隠す」ことになるため（Issue #6 download節6）、ここでは
/// 常に成功したかのように振る舞う。診断情報の出力はこの層の責務ではなく、標準エラー出力へ
/// 書くのはプロトコル層・CLI層の役目である（CLAUDE.md「標準出力の規律」）。
pub(crate) fn 一時ファイルを可能な限り削除する(対象: &一時ファイルパス) {
    let _ = std::fs::remove_file(対象.パス());
}
