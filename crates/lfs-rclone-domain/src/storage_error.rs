//! 保管操作全体で使うエラー分類。Issue #2の10節が正本である。

use crate::expected_byte_count::期待バイト数;
use crate::object_identifier::オブジェクト識別子;

/// 保管操作の失敗を分類する。object単位の失敗として`event=complete`の`error`へ変換される
/// ことを想定し、秘密情報を含まない説明文だけを持つ。
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum 保管エラー {
    #[error("設定不備: {説明}")]
    設定不備 { 説明: String },

    #[error("認証または接続に失敗しました: {説明}")]
    認証接続 { 説明: String },

    #[error("オブジェクトが存在しません: {識別子:?}")]
    未存在 { 識別子: オブジェクト識別子 },

    #[error("整合性エラー: {0}")]
    整合性(整合性エラー),

    #[error("ローカル入出力に失敗しました: {説明}")]
    ローカル入出力 { 説明: String },

    #[error("子プロセスの実行に失敗しました: {説明}")]
    子プロセス { 説明: String },
}

/// 期待値と実測値が一致しないことを表す整合性エラーの内訳。
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum 整合性エラー {
    #[error("オブジェクト識別子として不正な文字列です: {入力文字列}")]
    不正な識別子形式 { 入力文字列: String },

    #[error("バイト数が一致しません(期待: {期待:?}, 実際: {実際:?})")]
    バイト数の不一致 { 期待: 期待バイト数, 実際: 期待バイト数 },

    #[error("内容ハッシュが一致しません(期待: {期待:?}, 実際: {実際:?})")]
    内容ハッシュの不一致 { 期待: オブジェクト識別子, 実際: オブジェクト識別子 },
}
