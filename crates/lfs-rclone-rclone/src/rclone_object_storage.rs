//! rcloneを子プロセスとして起動する`オブジェクト保管庫`の実装。判断1により設定ファイルの
//! 形式は知らず、依存は`lfs-rclone-domain`の型として構築時に受け取って保持する
//! （グローバルCLAUDE.md「サービスの依存保持とコールバックの限定」）。

use lfs_rclone_domain::{
    一時ファイルパス, オブジェクト状態, オブジェクト識別子, 保管エラー, 保管先基底パス, 整合性エラー, 期待バイト数, Rclone実行ファイルの場所,
    Rcloneリモート名, 検証済みローカルファイル, 転送タイムアウト,
};
use lfs_rclone_storage_port::{アップロード結果, オブジェクト保管庫};

use crate::download_transfer;
use crate::existence_query;
use crate::finalize_transfer;
use crate::rclone_process_runner::Rcloneプロセス実行器;
use crate::upload_transfer;

/// rcloneを子プロセスとして起動する保管庫。実行ファイル・リモート名・保管先基底パス・
/// 転送タイムアウトをコンストラクタで受け取り保持する。
///
/// ダウンロード先のローカル一時ファイルパスは呼び出し側（`資産転送サービス`）が払い出す。
/// その置き場所はGit LFSがrenameで奪う先と同じボリュームでなければならず、保管先の設定
/// からは決まらないため、この保管庫は置き場所を持たない。
pub struct Rclone保管庫 {
    実行器: Rcloneプロセス実行器,
    リモート名: Rcloneリモート名,
    基底パス: 保管先基底パス,
}

impl Rclone保管庫 {
    pub fn 生成する(
        実行ファイル: Rclone実行ファイルの場所,
        リモート名: Rcloneリモート名,
        基底パス: 保管先基底パス,
        タイムアウト: 転送タイムアウト,
    ) -> Self {
        Self { 実行器: Rcloneプロセス実行器::生成する(実行ファイル, タイムアウト), リモート名, 基底パス }
    }
}

impl オブジェクト保管庫 for Rclone保管庫 {
    fn 存在を確認する(&self, 識別子: &オブジェクト識別子, 期待バイト数: 期待バイト数) -> Result<オブジェクト状態, 保管エラー> {
        let パス = self.基底パス.オブジェクトパスを求める(識別子);
        let 実測 = existence_query::最終オブジェクトの存在を問い合わせる(&self.実行器, &self.リモート名, &パス)?;
        Ok(状態を判定する(実測, 期待バイト数))
    }

    fn アップロードする(&self, 識別子: &オブジェクト識別子, 転送元: &検証済みローカルファイル) -> Result<アップロード結果, 保管エラー> {
        match self.存在を確認する(識別子, 転送元.バイト数())? {
            オブジェクト状態::存在 => return Ok(アップロード結果::既存),
            オブジェクト状態::サイズの不一致 { 実サイズ } => return Err(サイズ不一致を整合性エラーにする(転送元.バイト数(), 実サイズ)),
            オブジェクト状態::未存在 => {}
        }

        let 一時パス = self.基底パス.一時アップロード先を払い出す();
        upload_transfer::ローカル入力を一時オブジェクトパスへ転送する(&self.実行器, &self.リモート名, 転送元.パス(), &一時パス)?;

        let 最終パス = self.基底パス.オブジェクトパスを求める(識別子);
        let 最終化結果 =
            finalize_transfer::一時オブジェクトパスから最終オブジェクトパスへ移す(&self.実行器, &self.リモート名, &一時パス, &最終パス);

        match self.存在を確認する(識別子, 転送元.バイト数())? {
            オブジェクト状態::存在 => Ok(アップロード結果::転送済み),
            オブジェクト状態::サイズの不一致 { 実サイズ } => Err(サイズ不一致を整合性エラーにする(転送元.バイト数(), 実サイズ)),
            オブジェクト状態::未存在 => Err(最終化結果.err().unwrap_or_else(|| 保管エラー::子プロセス {
                説明: "最終化(moveto)の後に最終オブジェクトが見つかりませんでした".to_owned(),
            })),
        }
    }

    fn ダウンロードする(&self, 識別子: &オブジェクト識別子, 期待バイト数: 期待バイト数, 保存先: &一時ファイルパス) -> Result<(), 保管エラー> {
        match self.存在を確認する(識別子, 期待バイト数)? {
            オブジェクト状態::未存在 => return Err(保管エラー::未存在 { 識別子: 識別子.clone() }),
            オブジェクト状態::サイズの不一致 { 実サイズ } => return Err(サイズ不一致を整合性エラーにする(期待バイト数, 実サイズ)),
            オブジェクト状態::存在 => {}
        }

        let 最終パス = self.基底パス.オブジェクトパスを求める(識別子);
        download_transfer::最終オブジェクトを一時ファイルパスへ転送する(&self.実行器, &self.リモート名, &最終パス, 保存先)
    }
}

fn 状態を判定する(実測: Option<期待バイト数>, 期待バイト数: 期待バイト数) -> オブジェクト状態 {
    match 実測 {
        None => オブジェクト状態::未存在,
        Some(実サイズ) if 実サイズ == 期待バイト数 => オブジェクト状態::存在,
        Some(実サイズ) => オブジェクト状態::サイズの不一致 { 実サイズ },
    }
}

fn サイズ不一致を整合性エラーにする(期待: 期待バイト数, 実際: 期待バイト数) -> 保管エラー {
    保管エラー::整合性(整合性エラー::バイト数の不一致 { 期待, 実際 })
}
