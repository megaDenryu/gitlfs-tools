//! `doctor`の保管先書き込み確認だけが使う、OS標準の一時領域の下のローカル作業領域。
//!
//! ここへ置くファイルは数十バイトの確認用データであり、確認の最後に自分で削除する。
//! 所有権を他のプロセスへ渡さないため、ダウンロードの一時ファイルと違ってリポジトリと
//! 同じボリュームにある必要がない。`std::env::temp_dir`の直叩きをこの境界だけへ集約する
//! （グローバルCLAUDE.md「暗黙のグローバル依存を関数の奥で直叩きしない」）。

use lfs_rclone_domain::一時ディレクトリ;

const 作業領域の名前: &str = "git-lfs-rclone-storage-doctor";

pub(crate) fn 書き込み確認用の作業領域() -> 一時ディレクトリ {
    一時ディレクトリ::生成する(std::env::temp_dir().join(作業領域の名前))
}
