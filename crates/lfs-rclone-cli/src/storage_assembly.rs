//! PC設定が選んだ方式の保管庫を組み立て、その方式に意味のある起動確認を行う。
//! `転送セッション初期化境界::開始する`の一手続きとして呼ばれる私有ヘルパーである
//! （グローバルCLAUDE.md「サービスの依存保持とコールバックの限定」条1: 親のサービス型が
//! 依存を保持した上での工程ヘルパー）。
//!
//! ローカルディレクトリ方式では子プロセスを起動しないため、rcloneの起動確認は行わない。
//! 代わりに保管先の基点が実在するかを確かめる（マウントされていないドライブを指したまま
//! 転送を始めると、実体がどこへ落ちたのか利用者に分からなくなる）。

use lfs_rclone_config::{PCプロファイル, 保管先の指定};
use lfs_rclone_local::{ローカルディレクトリ保管庫, ローカル保管先ルートディレクトリ};
use lfs_rclone_protocol::初期化エラー;
use lfs_rclone_rclone::Rclone保管庫;

use crate::object_storage_selection::選択された保管庫;
use crate::rclone_startup_check::{rclone実行ファイルの起動可否を確かめる, rcloneの起動を確認する};

/// 起動確認を行わずに保管庫だけを組み立てる。`doctor`の保管先オブジェクト数の表示に使う。
/// `doctor`は同じ実行の中で保管先への到達確認と書き込み確認を別項目として済ませており、
/// ここで同じ確認を繰り返すと、rclone子プロセス方式で無駄な起動が増える。
pub(crate) fn 起動確認を伴わずに保管庫を組み立てる(プロファイル: &PCプロファイル) -> 選択された保管庫 {
    match プロファイル.保管先() {
        保管先の指定::Rclone子プロセス { リモート名, 実行ファイル, 転送タイムアウト } => {
            選択された保管庫::Rclone子プロセス(Rclone保管庫::生成する(
                実行ファイル.clone(),
                リモート名.clone(),
                プロファイル.基底パス().clone(),
                *転送タイムアウト,
            ))
        }
        保管先の指定::ローカルディレクトリ { ルートディレクトリ } => {
            選択された保管庫::ローカルディレクトリ(ローカルディレクトリ保管庫::生成する(
                ローカル保管先ルートディレクトリ::生成する(ルートディレクトリ.パス()),
                プロファイル.基底パス().clone(),
            ))
        }
    }
}

pub(crate) fn 起動確認を済ませた保管庫を組み立てる(プロファイル: &PCプロファイル) -> Result<選択された保管庫, 初期化エラー> {
    match プロファイル.保管先() {
        保管先の指定::Rclone子プロセス { リモート名, 実行ファイル, 転送タイムアウト } => {
            rclone実行ファイルの起動可否を確かめる(実行ファイル)?;
            let 保管庫 = Rclone保管庫::生成する(
                実行ファイル.clone(),
                リモート名.clone(),
                プロファイル.基底パス().clone(),
                *転送タイムアウト,
            );
            rcloneの起動を確認する(&保管庫).map_err(初期化エラー::保管失敗)?;
            Ok(選択された保管庫::Rclone子プロセス(保管庫))
        }
        保管先の指定::ローカルディレクトリ { ルートディレクトリ } => {
            let ルート = ローカル保管先ルートディレクトリ::生成する(ルートディレクトリ.パス());
            ルート.実在を確かめる().map_err(初期化エラー::保管失敗)?;
            Ok(選択された保管庫::ローカルディレクトリ(ローカルディレクトリ保管庫::生成する(
                ルート,
                プロファイル.基底パス().clone(),
            )))
        }
    }
}
