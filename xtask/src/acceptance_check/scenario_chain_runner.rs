//! 項目1〜6を、前項目の成否に応じて連鎖させて実行する。前提が崩れた項目は実行せず
//! 「未実施」として報告する（Issue #2 14節の番号順）。

use crate::acceptance_check::check_result::検査結果;
use crate::acceptance_check::scenario_state::主鎖状態;
use crate::acceptance_check::workspace::一時作業域;

pub fn 主鎖を実行する(状態: &mut 主鎖状態, 作業域: &一時作業域) -> (Vec<検査結果>, Vec<String>) {
    let ルート = 作業域.ルート().to_path_buf();
    let mut 結果一覧 = Vec::new();
    let mut 所見一覧 = Vec::new();

    let 項目1 = 検査結果::生成する(
        1,
        "新しい隔離Gitリポジトリでcommitにpointerだけが入る",
        "Git commitのblobはpointer本文であり、working treeの実ファイルはそれより大きい",
        状態.項目1_pointerのみコミットする(&ルート),
    );
    let 合格1 = 項目1.合格したか();
    結果一覧.push(項目1);

    let 項目2 = 段階実行する(合格1, 2, "PC A相当のpushで実体が1個だけ作られる", "保管先のcontent-addressedなパスへオブジェクトが1個だけ作られる", "項目1が失敗したため実行しなかった", || {
        状態.項目2_push後に実体が1個だけ作られる(&ルート)
    });
    let 合格2 = 項目2.合格したか();
    結果一覧.push(項目2);

    if 合格2 {
        match 状態.通常cloneの可否を調べる(作業域) {
            Ok(所見) => 所見一覧.push(所見),
            Err(エラー) => 所見一覧.push(format!("通常のgit cloneの検証自体が失敗した: {エラー}")),
        }
    }

    let 項目3 = 段階実行する(合格2, 3, "PC B相当のcloneで同一SHA-256・バイト数を取得できる", "PC AとPC Bの取得物のSHA-256とバイト数が一致し、ダウンロードの一時ファイルがリポジトリと同じボリュームに置かれる", "項目2が失敗したため実行しなかった", || {
        状態.項目3_pcbで同一内容を取得する(&ルート)
    });
    let 合格3 = 項目3.合格したか();
    結果一覧.push(項目3);

    let 項目4 = 段階実行する(合格3, 4, "PC Bの更新で新オブジェクトが追加され旧オブジェクトは残る", "新oidのオブジェクトが追加され、旧oidのオブジェクトは変化しない", "項目3が失敗したため実行しなかった", || {
        状態.項目4_pcbの更新で新オブジェクトが追加される()
    });
    let 合格4 = 項目4.合格したか();
    結果一覧.push(項目4);

    let 項目5 = 段階実行する(合格4, 5, "PC A相当で新旧commitを切り替え双方を復元できる", "新commitと旧commitのどちらへcheckoutしても正しい内容が復元できる", "項目4が失敗したため実行しなかった", || {
        状態.項目5_新旧commitを復元する()
    });
    let 合格5 = 項目5.合格したか();
    結果一覧.push(項目5);

    let 項目6 = 段階実行する(合格5, 6, "同じoidを再pushしても重複オブジェクトが増えない", "再push前後で保管先のオブジェクト一覧が変化しない", "項目5が失敗したため実行しなかった", || {
        状態.項目6_同一oid再pushで重複しない()
    });
    結果一覧.push(項目6);

    (結果一覧, 所見一覧)
}

fn 段階実行する(
    前提が合格: bool,
    番号: u8,
    表題: &'static str,
    期待した結果: &str,
    未実施理由: &str,
    検査: impl FnOnce() -> Result<String, String>,
) -> 検査結果 {
    if 前提が合格 {
        検査結果::生成する(番号, 表題, 期待した結果, 検査())
    } else {
        検査結果::未実施(番号, 表題, 期待した結果, 未実施理由)
    }
}
