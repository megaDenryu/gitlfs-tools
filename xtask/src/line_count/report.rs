//! 検査結果の報告。違反があれば1件ずつ標準エラー出力へ書いてエラーで終える。
//! 違反がなければ、検査件数と100行に近い上位ファイルを標準出力へ書いて正常終了する。

use crate::line_count::code_line_measurement::実測行数;
use crate::line_count::line_count_limit::行数上限;
use crate::line_count::violation::行数違反;

const 上位表示件数: usize = 5;

pub fn 結果を報告する(実測一覧: &[実測行数], 違反一覧: &[行数違反]) -> Result<(), String> {
    if !違反一覧.is_empty() {
        for 違反 in 違反一覧 {
            eprintln!("{}", 違反を文字列にする(違反));
        }
        return Err(format!("行数の原則違反が{}件見つかった", 違反一覧.len()));
    }

    println!("検査したファイル数: {}", 実測一覧.len());
    println!("100行に最も近い上位{上位表示件数}件:");

    let mut 近い順実測一覧: Vec<&実測行数> = 実測一覧.iter().collect();
    近い順実測一覧.sort_by_key(|実測| 実測.行数.上限との差(行数上限::原則()));

    for 実測 in 近い順実測一覧.into_iter().take(上位表示件数) {
        println!("  {} ({}行)", 実測.ファイル, 実測.行数.数値());
    }

    Ok(())
}

fn 違反を文字列にする(違反: &行数違反) -> String {
    match 違反 {
        行数違反::未登録の超過 { ファイル, 実測 } => {
            format!("違反: {ファイル} が{}行あり、100行を超えているが台帳に未登録", 実測.数値())
        }
        行数違反::登録上限を超えた超過 { ファイル, 実測, 上限 } => {
            format!(
                "違反: {ファイル} が{}行あり、台帳の上限{}行を超えている",
                実測.数値(),
                上限.数値()
            )
        }
        行数違反::陳腐化した登録 { ファイル, 実測 } => {
            format!(
                "違反: {ファイル} は{}行に収まっており、台帳の登録が陳腐化している。台帳から削除すること",
                実測.数値()
            )
        }
        行数違反::存在しない登録ファイル { ファイル } => {
            format!("違反: 台帳に登録された{ファイル}が存在しない")
        }
        行数違反::台帳の上限が過大 { ファイル, 上限 } => {
            format!(
                "違反: {ファイル}の台帳登録の上限が{}行あり、150行の上限を超えている",
                上限.数値()
            )
        }
    }
}
