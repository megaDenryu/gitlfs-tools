//! アップロード完了を表す値型。

use lfs_rclone_domain::オブジェクト識別子;
use lfs_rclone_storage_port::アップロード結果;

/// アップロード操作が成功したことを表す完了値。転送を実際に行ったか、既存オブジェクトで
/// 済んだかは`結果()`（`アップロード結果::転送済み` / `既存`）で区別する。
pub struct アップロード完了 {
    識別子: オブジェクト識別子,
    結果: アップロード結果,
}

impl アップロード完了 {
    pub(crate) fn 生成する(識別子: オブジェクト識別子, 結果: アップロード結果) -> Self {
        Self { 識別子, 結果 }
    }

    pub fn 識別子(&self) -> &オブジェクト識別子 {
        &self.識別子
    }

    pub fn 結果(&self) -> アップロード結果 {
        self.結果
    }
}
