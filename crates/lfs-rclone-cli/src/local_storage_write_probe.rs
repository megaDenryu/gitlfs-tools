//! `doctor`の書き込み確認のローカルディレクトリ方式版。一時オブジェクトの領域
//! （`<基底パス>/lfs/tmp/<UUID>`）だけを使い、書き込み・読み戻し・削除を標準ライブラリの
//! ファイル操作で行う。最終オブジェクトの領域（`lfs/objects/...`）へは書かない
//! （`保管先基底パス::オブジェクトパスを求める`を一度も呼ばないことで担保する）。

use lfs_rclone_domain::{保管エラー, 保管先基底パス};
use lfs_rclone_local::{保管先オブジェクトのローカルファイルパス, ローカル保管先ルートディレクトリ};

use crate::storage_write_probe::{確認用のペイロード, 書き込み確認結果};

/// 保管先の基点を保持し、その中の一時領域へ実際に書けるかを確かめる。
pub(crate) struct ローカル保管先の書き込み確認 {
    ルートディレクトリ: ローカル保管先ルートディレクトリ,
}

impl ローカル保管先の書き込み確認 {
    pub(crate) fn 生成する(ルートディレクトリ: ローカル保管先ルートディレクトリ) -> Self {
        Self { ルートディレクトリ }
    }

    pub(crate) fn 一時オブジェクトで確認する(&self, 基底パス: &保管先基底パス) -> Result<書き込み確認結果, 保管エラー> {
        self.ルートディレクトリ.実在を確かめる()?;
        let 一時オブジェクト =
            保管先オブジェクトのローカルファイルパス::保管先オブジェクトパスから生成する(&基底パス.一時アップロード先を払い出す());

        let 確認結果 = 書き込みと読み戻しを試みる(&一時オブジェクト);
        let 片付け結果 = 一時オブジェクト.実体を削除する();

        確認結果?;
        Ok(match 片付け結果 {
            Ok(()) => 書き込み確認結果::問題なし,
            Err(エラー) => 書き込み確認結果::片付け残り { 説明: エラー.to_string() },
        })
    }
}

fn 書き込みと読み戻しを試みる(一時オブジェクト: &保管先オブジェクトのローカルファイルパス) -> Result<(), 保管エラー> {
    一時オブジェクト.中間ディレクトリを用意する()?;
    std::fs::write(一時オブジェクト.パス(), 確認用のペイロード).map_err(|エラー| 保管エラー::ローカル入出力 {
        説明: format!("保管先への確認用データの書き込みに失敗しました: {エラー}"),
    })?;

    let 読み戻し内容 = std::fs::read(一時オブジェクト.パス()).map_err(|エラー| 保管エラー::ローカル入出力 {
        説明: format!("保管先から確認用データを読み戻せませんでした: {エラー}"),
    })?;

    if 読み戻し内容 == 確認用のペイロード {
        Ok(())
    } else {
        Err(保管エラー::ローカル入出力 { 説明: "読み戻した内容が書き込んだ内容と一致しません".to_owned() })
    }
}
