//! 標準ライブラリのファイル操作だけで動く`オブジェクト保管庫`の実装。子プロセスを起動しない。
//!
//! 振る舞いはrcloneの実装（`lfs-rclone-rclone`の`Rclone保管庫`）と揃える。未存在・存在・
//! サイズ不一致の区別、一時パスを経由した配置、同一内容を再転送しないこと、最終パスが競合
//! してもバイト数が一致すれば成功として扱うことのすべてが同じである。

use lfs_rclone_domain::{
    一時ファイルパス, オブジェクト状態, オブジェクト識別子, 保管エラー, 保管先基底パス, 整合性エラー, 期待バイト数, 検証済みローカルファイル,
};
use lfs_rclone_storage_port::{アップロード結果, オブジェクト保管庫, 保管オブジェクト総数};

use crate::local_object_directory::保管先オブジェクト置き場のローカルディレクトリ;
use crate::local_object_file_path::保管先オブジェクトのローカルファイルパス;
use crate::local_storage_root::ローカル保管先ルートディレクトリ;
use crate::upload_placement::一時パス経由の配置;

/// ローカルファイルシステム上のディレクトリを保管先とする保管庫。基点のディレクトリと
/// パスの綴りを構築時に受け取り保持する（グローバルCLAUDE.md「サービスの依存保持と
/// コールバックの限定」）。
pub struct ローカルディレクトリ保管庫 {
    ルートディレクトリ: ローカル保管先ルートディレクトリ,
    基底パス: 保管先基底パス,
}

impl ローカルディレクトリ保管庫 {
    pub fn 生成する(ルートディレクトリ: ローカル保管先ルートディレクトリ, 基底パス: 保管先基底パス) -> Self {
        Self { ルートディレクトリ, 基底パス }
    }

    fn 最終ファイルパスを求める(&self, 識別子: &オブジェクト識別子) -> 保管先オブジェクトのローカルファイルパス {
        保管先オブジェクトのローカルファイルパス::保管先オブジェクトパスから生成する(&self.基底パス.オブジェクトパスを求める(識別子))
    }

    fn 一時ファイルパスを払い出す(&self) -> 保管先オブジェクトのローカルファイルパス {
        保管先オブジェクトのローカルファイルパス::保管先オブジェクトパスから生成する(&self.基底パス.一時アップロード先を払い出す())
    }
}

impl オブジェクト保管庫 for ローカルディレクトリ保管庫 {
    fn 存在を確認する(&self, 識別子: &オブジェクト識別子, 期待バイト数: 期待バイト数) -> Result<オブジェクト状態, 保管エラー> {
        self.ルートディレクトリ.実在を確かめる()?;
        let 実測 = self.最終ファイルパスを求める(識別子).実バイト数を調べる()?;
        Ok(状態を判定する(実測, 期待バイト数))
    }

    fn 保管しているオブジェクトの総数を数える(&self) -> Result<保管オブジェクト総数, 保管エラー> {
        self.ルートディレクトリ.実在を確かめる()?;
        保管先オブジェクト置き場のローカルディレクトリ::保管先オブジェクトパスから生成する(&self.基底パス.オブジェクト置き場のパスを求める())
            .配下のオブジェクトを数える()
    }

    fn アップロードする(&self, 識別子: &オブジェクト識別子, 転送元: &検証済みローカルファイル) -> Result<アップロード結果, 保管エラー> {
        match self.存在を確認する(識別子, 転送元.バイト数())? {
            オブジェクト状態::存在 => return Ok(アップロード結果::既存),
            オブジェクト状態::サイズの不一致 { 実サイズ } => return Err(サイズ不一致を整合性エラーにする(転送元.バイト数(), 実サイズ)),
            オブジェクト状態::未存在 => {}
        }

        let 配置 = 一時パス経由の配置::生成する(self.一時ファイルパスを払い出す(), self.最終ファイルパスを求める(識別子));
        let 配置結果 = 配置.ローカル入力を最終パスへ置く(転送元.パス());

        match self.存在を確認する(識別子, 転送元.バイト数())? {
            オブジェクト状態::存在 => Ok(アップロード結果::転送済み),
            オブジェクト状態::サイズの不一致 { 実サイズ } => Err(サイズ不一致を整合性エラーにする(転送元.バイト数(), 実サイズ)),
            オブジェクト状態::未存在 => Err(配置結果.err().unwrap_or_else(|| 保管エラー::ローカル入出力 {
                説明: "最終パスへの移動の後に最終オブジェクトが見つかりませんでした".to_owned(),
            })),
        }
    }

    fn ダウンロードする(&self, 識別子: &オブジェクト識別子, 期待バイト数: 期待バイト数, 保存先: &一時ファイルパス) -> Result<(), 保管エラー> {
        match self.存在を確認する(識別子, 期待バイト数)? {
            オブジェクト状態::未存在 => return Err(保管エラー::未存在 { 識別子: 識別子.clone() }),
            オブジェクト状態::サイズの不一致 { 実サイズ } => return Err(サイズ不一致を整合性エラーにする(期待バイト数, 実サイズ)),
            オブジェクト状態::存在 => {}
        }
        if 保存先.パス().exists() {
            return Err(保管エラー::ローカル入出力 { 説明: "ダウンロード先が既に存在します".to_owned() });
        }

        std::fs::copy(self.最終ファイルパスを求める(識別子).パス(), 保存先.パス()).map_err(|エラー| 保管エラー::ローカル入出力 {
            説明: format!("保管先からダウンロード先への複製に失敗しました: {エラー}"),
        })?;
        Ok(())
    }
}

fn 状態を判定する(実測: Option<期待バイト数>, 期待バイト数: 期待バイト数) -> オブジェクト状態 {
    match 実測 {
        None => オブジェクト状態::未存在,
        Some(実サイズ) if 実サイズ == 期待バイト数 => オブジェクト状態::存在,
        Some(実サイズ) => オブジェクト状態::サイズの不一致 { 実サイズ },
    }
}

fn サイズ不一致を整合性エラーにする(期待: 期待バイト数, 実際: 期待バイト数) -> 保管エラー {
    保管エラー::整合性(整合性エラー::バイト数の不一致 { 期待, 実際 })
}
