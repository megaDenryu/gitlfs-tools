//! 期待値と実測値が一致しないことを表す整合性エラー。保管操作の失敗（`保管エラー`）に
//! 限定されず、Git LFSプロトコルから受け取った文字列の構文検証等、保管操作が始まる前の
//! 解析でも独立して使う。

use crate::expected_byte_count::期待バイト数;
use crate::object_identifier::オブジェクト識別子;

/// 期待値と実測値が一致しないことを表す整合性エラーの内訳。
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum 整合性エラー {
    #[error("オブジェクト識別子として不正な文字列です: {入力文字列}")]
    不正な識別子形式 { 入力文字列: String },

    #[error("バイト数が一致しません(期待: {期待:?}, 実際: {実際:?})")]
    バイト数の不一致 { 期待: 期待バイト数, 実際: 期待バイト数 },

    #[error("内容ハッシュが一致しません(期待: {期待:?}, 実際: {実際:?})")]
    内容ハッシュの不一致 { 期待: オブジェクト識別子, 実際: オブジェクト識別子 },
}
