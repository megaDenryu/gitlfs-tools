//! `オブジェクト状態`を期待バイト数と突き合わせ、整合性エラーへ変換する判定。
//! `資産転送サービス`だけが使う内部ヘルパーであり、外部へは公開しない。

use lfs_rclone_domain::{オブジェクト状態, オブジェクト識別子, 保管エラー, 整合性エラー, 期待バイト数};

/// `オブジェクト状態`はdomainクレートが定義する型であり、このクレートからinherentメソッドを
/// 生やせない（孤児則）。ローカルなtraitとして拡張することで、呼び出し側は
/// `状態.期待どおりの存在であることを確認する(...)`という自然な主語のmethod chainで読める
/// （グローバルCLAUDE.md「Rust表現の選択」条2・条4）。
pub(crate) trait オブジェクト状態の整合性判定 {
    /// 期待バイト数と一致する`存在`だけを成功とする。`未存在`は`保管エラー::未存在`へ、
    /// `サイズの不一致`は`保管エラー::整合性`へ変換する。
    fn 期待どおりの存在であることを確認する(self, 識別子: &オブジェクト識別子, 期待バイト数: 期待バイト数) -> Result<(), 保管エラー>;
}

impl オブジェクト状態の整合性判定 for オブジェクト状態 {
    fn 期待どおりの存在であることを確認する(self, 識別子: &オブジェクト識別子, 期待バイト数: 期待バイト数) -> Result<(), 保管エラー> {
        match self {
            オブジェクト状態::存在 => Ok(()),
            オブジェクト状態::未存在 => Err(保管エラー::未存在 { 識別子: 識別子.clone() }),
            オブジェクト状態::サイズの不一致 { 実サイズ } => Err(保管エラー::整合性(整合性エラー::バイト数の不一致 {
                期待: 期待バイト数,
                実際: 実サイズ,
            })),
        }
    }
}
