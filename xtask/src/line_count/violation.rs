//! 例外台帳と実測行数を突き合わせ、行数原則への違反を判定する。

use crate::line_count::code_line_count::コード行数;
use crate::line_count::code_line_measurement::実測行数;
use crate::line_count::exception_ledger::台帳;
use crate::line_count::line_count_limit::行数上限;
use crate::line_count::relative_rust_file_path::相対rustファイルパス;

pub enum 行数違反 {
    未登録の超過 { ファイル: 相対rustファイルパス, 実測: コード行数 },
    登録上限を超えた超過 { ファイル: 相対rustファイルパス, 実測: コード行数, 上限: 行数上限 },
    陳腐化した登録 { ファイル: 相対rustファイルパス, 実測: コード行数 },
    存在しない登録ファイル { ファイル: 相対rustファイルパス },
    台帳の上限が過大 { ファイル: 相対rustファイルパス, 上限: 行数上限 },
}

impl 台帳 {
    pub fn 違反を判定する(&self, 実測一覧: &[実測行数]) -> Vec<行数違反> {
        let mut 違反一覧 = Vec::new();

        for 登録 in &self.登録一覧 {
            if 登録.上限.数値() > 行数上限::台帳の許容上限().数値() {
                違反一覧.push(行数違反::台帳の上限が過大 {
                    ファイル: 登録.ファイル.clone(),
                    上限: 登録.上限,
                });
            }

            match 実測一覧.iter().find(|実測| 実測.ファイル == 登録.ファイル) {
                None => 違反一覧.push(行数違反::存在しない登録ファイル { ファイル: 登録.ファイル.clone() }),
                Some(実測) if !実測.行数.上限を超えているか(行数上限::原則()) => {
                    違反一覧.push(行数違反::陳腐化した登録 {
                        ファイル: 登録.ファイル.clone(),
                        実測: 実測.行数,
                    });
                }
                Some(実測) if 実測.行数.上限を超えているか(登録.上限) => {
                    違反一覧.push(行数違反::登録上限を超えた超過 {
                        ファイル: 登録.ファイル.clone(),
                        実測: 実測.行数,
                        上限: 登録.上限,
                    });
                }
                Some(_) => {}
            }
        }

        for 実測 in 実測一覧 {
            let 登録済みか = self.登録一覧.iter().any(|登録| 登録.ファイル == 実測.ファイル);
            if !登録済みか && 実測.行数.上限を超えているか(行数上限::原則()) {
                違反一覧.push(行数違反::未登録の超過 { ファイル: 実測.ファイル.clone(), 実測: 実測.行数 });
            }
        }

        違反一覧
    }
}
