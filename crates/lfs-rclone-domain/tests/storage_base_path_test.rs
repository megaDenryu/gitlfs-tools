//! `保管先基底パス`のオブジェクトパス導出と一時アップロード先払い出しのテスト。

use lfs_rclone_domain::{オブジェクト識別子, 保管先基底パス};

/// 16進16文字("0123456789abcdef")を4回繰り返した、正確に64文字の妥当な識別子文字列。
/// 手打ちの64文字リテラルは文字数を誤りやすいため、繰り返しで構成する。
fn 識別子文字列() -> String {
    "0123456789abcdef".repeat(4)
}

#[test]
fn オブジェクト識別子から先頭2文字と次の2文字で分割した最終パスを導く() -> Result<(), Box<dyn std::error::Error>> {
    let 基底パス = 保管先基底パス::生成する("mega-assets:git-lfs-rclone-storage")?;
    let 識別子文字列 = 識別子文字列();
    let 識別子 = オブジェクト識別子::生成する(&識別子文字列)?;

    let 最終パス = 基底パス.オブジェクトパスを求める(&識別子);

    assert_eq!(
        最終パス.文字列表現(),
        format!(
            "mega-assets:git-lfs-rclone-storage/lfs/objects/sha256/{}/{}/{}",
            &識別子文字列[0..2],
            &識別子文字列[2..4],
            識別子文字列
        )
    );
    Ok(())
}

#[test]
fn 末尾に区切り文字がある基底パスとない基底パスは同じ最終パスを導く() -> Result<(), Box<dyn std::error::Error>> {
    let 末尾ありの基底パス = 保管先基底パス::生成する("base/path/")?;
    let 末尾なしの基底パス = 保管先基底パス::生成する("base/path")?;
    let 識別子 = オブジェクト識別子::生成する(&識別子文字列())?;

    assert_eq!(
        末尾ありの基底パス.オブジェクトパスを求める(&識別子).文字列表現(),
        末尾なしの基底パス.オブジェクトパスを求める(&識別子).文字列表現(),
    );
    Ok(())
}

#[test]
fn 一時アップロード先は呼ぶたびに異なる() -> Result<(), Box<dyn std::error::Error>> {
    let 基底パス = 保管先基底パス::生成する("base")?;

    let 一回目 = 基底パス.一時アップロード先を払い出す();
    let 二回目 = 基底パス.一時アップロード先を払い出す();

    assert_ne!(一回目.文字列表現(), 二回目.文字列表現());
    assert!(一回目.文字列表現().starts_with("base/lfs/tmp/"));
    Ok(())
}

#[test]
fn 空文字列の基底パスは設定不備として拒否される() {
    assert!(保管先基底パス::生成する("").is_err());
}
