//! ダウンロード完了を表す値型。

use std::path::Path;

use gitlfs_tools_domain::{オブジェクト識別子, 期待バイト数, 検証済みローカルファイル};

/// ダウンロード操作が成功したことを表す完了値。一時ファイルの所有権を呼び出し側へ渡す
/// （Issue #6 download節5「成功したときだけ、一時ファイルの所有権を呼び出し側へ渡せる
/// 完了値を返す」）。
///
/// 内部は`検証済みローカルファイル`（domain層。バイト数とSHA-256をオブジェクト識別子と照合し終えた
/// ローカルファイルを表す）をそのまま保持する。アップロード時の入力検証とダウンロード後の
/// 再検証はどちらも「識別子・バイト数・実測値を突き合わせ済みのローカルファイル」という
/// 同じ形の状態であるため、domain層に新しい型を追加せず既存の`検証済みローカルファイル`を再利用する。
pub struct ダウンロード完了 {
    検証済みファイル: 検証済みローカルファイル,
}

impl ダウンロード完了 {
    pub(crate) fn 生成する(検証済みファイル: 検証済みローカルファイル) -> Self {
        Self { 検証済みファイル }
    }

    pub fn 識別子(&self) -> &オブジェクト識別子 {
        self.検証済みファイル.識別子()
    }

    pub fn バイト数(&self) -> 期待バイト数 {
        self.検証済みファイル.バイト数()
    }

    /// 一時ファイルの絶対パス。所有権は呼び出し側へ渡っており、成功後にagentが削除しては
    /// ならない（Issue #2 3.4節）。
    pub fn パス(&self) -> &Path {
        self.検証済みファイル.パス()
    }
}
