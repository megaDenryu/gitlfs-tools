//! このcrateが扱う失敗種別（`保管エラー`・`整合性エラー`・`初期化エラー`・
//! `プロトコル解析エラー`）を、`error.code`と`error.message`として書き出せる形へ
//! 正規化する。書き込み側（`protocol_response_writer.rs`）はこの型だけを知ればよく、
//! 個々の失敗種別のバリアント構造を知らずに済む。

use gitlfs_tools_domain::{保管エラー, 整合性エラー};

use crate::error_code::エラーコード;
use crate::init_error::初期化エラー;
use crate::protocol_parse_error::プロトコル解析エラー;

pub(crate) struct 表示用エラー {
    コード: エラーコード,
    メッセージ: String,
}

impl 表示用エラー {
    pub(crate) fn コード(&self) -> エラーコード {
        self.コード
    }

    pub(crate) fn メッセージ(&self) -> &str {
        &self.メッセージ
    }
}

impl From<&保管エラー> for 表示用エラー {
    fn from(エラー: &保管エラー) -> Self {
        let コード = match エラー {
            保管エラー::設定不備 { .. } => エラーコード::保管設定不備,
            保管エラー::認証接続 { .. } => エラーコード::認証接続失敗,
            保管エラー::未存在 { .. } => エラーコード::オブジェクト未存在,
            保管エラー::整合性(整合性) => return Self::from(整合性),
            保管エラー::ローカル入出力 { .. } => エラーコード::ローカル入出力失敗,
            保管エラー::子プロセス { .. } => エラーコード::Rcloneプロセス実行失敗,
        };
        Self { コード, メッセージ: エラー.to_string() }
    }
}

impl From<&整合性エラー> for 表示用エラー {
    fn from(エラー: &整合性エラー) -> Self {
        let コード = match エラー {
            整合性エラー::不正な識別子形式 { .. } => エラーコード::不正な識別子形式,
            整合性エラー::バイト数の不一致 { .. } => エラーコード::バイト数の不一致,
            整合性エラー::内容ハッシュの不一致 { .. } => エラーコード::内容ハッシュの不一致,
        };
        Self { コード, メッセージ: エラー.to_string() }
    }
}

impl From<&初期化エラー> for 表示用エラー {
    fn from(エラー: &初期化エラー) -> Self {
        let コード = match エラー {
            初期化エラー::プロジェクト設定未検出 { .. } => エラーコード::プロジェクト設定未検出,
            初期化エラー::PC設定未検出 { .. } => エラーコード::PC設定未検出,
            初期化エラー::PC設定ディレクトリ不明 { .. } => エラーコード::PC設定ディレクトリ不明,
            初期化エラー::設定解析失敗 { .. } => エラーコード::設定解析失敗,
            初期化エラー::未対応スキーマ版 { .. } => エラーコード::未対応スキーマ版,
            初期化エラー::未定義プロファイル { .. } => エラーコード::未定義プロファイル,
            初期化エラー::設定読み込み入出力失敗 { .. } => エラーコード::設定読み込み入出力失敗,
            初期化エラー::Rclone実行ファイル不在 { .. } => エラーコード::Rclone実行ファイル不在,
            初期化エラー::保管失敗(保管) => return Self::from(保管),
        };
        Self { コード, メッセージ: エラー.to_string() }
    }
}

impl From<&プロトコル解析エラー> for 表示用エラー {
    fn from(エラー: &プロトコル解析エラー) -> Self {
        let コード = match エラー {
            プロトコル解析エラー::JSON解析失敗 { .. } => エラーコード::JSON解析失敗,
            プロトコル解析エラー::未知のevent { .. } => エラーコード::未知のevent,
            プロトコル解析エラー::必須フィールド欠落または不正 { .. } => エラーコード::必須フィールド欠落または不正,
        };
        Self { コード, メッセージ: エラー.to_string() }
    }
}
