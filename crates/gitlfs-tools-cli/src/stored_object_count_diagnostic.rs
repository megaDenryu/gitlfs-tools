//! `doctor`が保管先のオブジェクト数を表示する項目（Issue #12）。
//!
//! この項目は合否を判定しない。数が0でも、まだ1件もアップロードしていないだけかもしれず、
//! 「まだ送っていない」と「送ったものが消えた」を件数だけでは区別できないためである。
//! 区別できないものを合否に使うと、導入の直後に必ず落ちる検査になる。数えた結果は
//! `診断結果::参考情報`として`[情報]`の行で出し、`[OK]`と紛れないようにする。
//!
//! 数える対象は保管先全体である。保管先は複数のリポジトリで共用するため、他のリポジトリが
//! 置いたオブジェクトもこの数に入る。そのことが読み取れる文言を添える。

use gitlfs_tools_config::PCプロファイル;
use gitlfs_tools_storage_port::オブジェクト保管庫;

use crate::diagnostic_finding::診断結果;
use crate::storage_assembly::起動確認を伴わずに保管庫を組み立てる;

const 項目名: &str = "保管先にあるオブジェクトの数";

pub(crate) fn 保管先にあるオブジェクトの数を診断する(プロファイル: Option<&PCプロファイル>) -> 診断結果 {
    let Some(プロファイル) = プロファイル else {
        return 参考情報の診断結果を作る("プロファイルが解決できていないため数えられませんでした");
    };

    match 起動確認を伴わずに保管庫を組み立てる(プロファイル).保管しているオブジェクトの総数を数える() {
        Ok(総数) => 参考情報の診断結果を作る(&format!("{総数}件(共用の保管先全体。他のリポジトリが置いた分を含む)")),
        Err(エラー) => 参考情報の診断結果を作る(&format!("数えられませんでした: {エラー}")),
    }
}

fn 参考情報の診断結果を作る(内容: &str) -> 診断結果 {
    診断結果::参考情報 { 項目: 項目名, 内容: 内容.to_owned() }
}
