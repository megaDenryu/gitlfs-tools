//! 保管境界のトレイト定義。

use gitlfs_tools_domain::{
    オブジェクト状態, オブジェクト識別子, 一時ファイルパス, 保管エラー, 期待バイト数, 検証済みローカルファイル,
};

use crate::stored_object_count::保管オブジェクト総数;
use crate::upload_result::アップロード結果;

/// 保管先（rcloneのリモート）へのオブジェクトの保存・取得を抽象化する境界。
/// 実装（rclone子プロセス起動等）は`gitlfs-tools-rclone`が持つ（アーキテクチャ.md 2節）。
pub trait オブジェクト保管庫 {
    /// 最終保存先でのオブジェクトの存在とバイト数を確認する。
    fn 存在を確認する(&self, 識別子: &オブジェクト識別子, 期待バイト数: 期待バイト数) -> Result<オブジェクト状態, 保管エラー>;

    /// 保管先のオブジェクト置き場に在るオブジェクトの総数を数える。
    ///
    /// 保管先は複数のリポジトリで共用するため、この数には他のリポジトリが置いたオブジェクトも
    /// 含まれる。特定のリポジトリが必要とするオブジェクトが在るかどうかは`存在を確認する`で
    /// 個別に見る（Issue #12「突き合わせの向きは片方向にする」）。
    fn 保管しているオブジェクトの総数を数える(&self) -> Result<保管オブジェクト総数, 保管エラー>;

    /// 検証済みのローカル入力を最終保存先へ置く。同じ内容が既に存在する場合は転送しない
    /// （判断5「保管先のオブジェクトは変更不能として扱う」）。
    fn アップロードする(&self, 識別子: &オブジェクト識別子, 転送元: &検証済みローカルファイル) -> Result<アップロード結果, 保管エラー>;

    /// 最終保存先のオブジェクトを、呼び出し側が用意した一時ファイルパスへ取得する。
    /// 既存の内容を無言で上書きしない（Issue #2 4節）。
    fn ダウンロードする(
        &self,
        識別子: &オブジェクト識別子,
        期待バイト数: 期待バイト数,
        保存先: &一時ファイルパス,
    ) -> Result<(), 保管エラー>;
}
