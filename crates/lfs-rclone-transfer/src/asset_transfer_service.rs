//! 資産転送サービス。アップロード・ダウンロードのユースケースを実装する（Issue #6）。
//! 標準入出力のJSON形式もrcloneのコマンドも知らない。`オブジェクト保管庫`だけへ依存する。

use lfs_rclone_domain::{一時ディレクトリ, オブジェクト状態, 整合性エラー, 検証前のローカルファイル};
use lfs_rclone_storage_port::{アップロード結果, オブジェクト保管庫};

use crate::download_completion::ダウンロード完了;
use crate::download_request::ダウンロード要求;
use crate::object_state_consistency::オブジェクト状態の整合性判定;
use crate::temp_file_cleanup::一時ファイルを可能な限り削除する;
use crate::upload_completion::アップロード完了;
use crate::upload_request::アップロード要求;
use crate::転送エラー;

/// アップロード・ダウンロードのユースケースを提供するサービス。保管庫と一時ファイル置き場を
/// 依存としてコンストラクタで保持する（グローバルCLAUDE.md「サービスの依存保持と
/// コールバックの限定」条1）。呼び出しのたびに保管庫を引数で受け取る自由関数の列にしない。
pub struct 資産転送サービス<保管庫> {
    保管庫: 保管庫,
    一時ファイル置き場: 一時ディレクトリ,
}

impl<保管庫: オブジェクト保管庫> 資産転送サービス<保管庫> {
    pub fn 生成する(保管庫: 保管庫, 一時ファイル置き場: 一時ディレクトリ) -> Self {
        Self { 保管庫, 一時ファイル置き場 }
    }

    /// 検証済みの入力を保管庫へアップロードする。同一内容が既に存在すれば転送せず成功として
    /// 扱う（Issue #2 判断5「保管先のオブジェクトは変更不能として扱う」）。転送を行った場合は
    /// 直後に保管先の実サイズを再確認し、他プロセスとの同時書き込みでサイズが食い違ったときは
    /// 成功として返さない（Issue #2 3.3節6項）。同じ入力での再実行は、1回目のアップロード後は
    /// 事前の存在確認で`既存`が返るため保管庫への転送呼び出しが増えず、最終状態も変わらない。
    pub fn アップロードする(&self, 要求: アップロード要求) -> Result<アップロード完了, 転送エラー> {
        let 転送元 = 要求.転送元を検証する()?;

        match self.保管庫.存在を確認する(転送元.識別子(), 転送元.バイト数())? {
            オブジェクト状態::存在 => {
                return Ok(アップロード完了::生成する(転送元.識別子().clone(), アップロード結果::既存));
            }
            オブジェクト状態::サイズの不一致 { 実サイズ } => {
                return Err(転送エラー::整合性(整合性エラー::バイト数の不一致 {
                    期待: 転送元.バイト数(),
                    実際: 実サイズ,
                }));
            }
            オブジェクト状態::未存在 => {}
        }

        let 結果 = self.保管庫.アップロードする(転送元.識別子(), &転送元)?;

        if let アップロード結果::転送済み = 結果 {
            self.保管庫
                .存在を確認する(転送元.識別子(), 転送元.バイト数())?
                .期待どおりの存在であることを確認する(転送元.識別子(), 転送元.バイト数())?;
        }

        Ok(アップロード完了::生成する(転送元.識別子().clone(), 結果))
    }

    /// 保管先のオブジェクトをagent管理の一時ファイルへダウンロードし、バイト数とSHA-256を
    /// 再検証する。失敗時は確保した一時ファイルを可能な限り削除する（Issue #2 3.4節）。
    pub fn ダウンロードする(&self, 要求: ダウンロード要求) -> Result<ダウンロード完了, 転送エラー> {
        self.保管庫
            .存在を確認する(要求.識別子(), 要求.バイト数())?
            .期待どおりの存在であることを確認する(要求.識別子(), 要求.バイト数())?;

        let 一時ファイル = self.一時ファイル置き場.固有の一時ファイルパスを払い出す();

        if let Err(エラー) = self
            .保管庫
            .ダウンロードする(要求.識別子(), 要求.バイト数(), &一時ファイル)
        {
            一時ファイルを可能な限り削除する(一時ファイル.パス());
            return Err(エラー);
        }

        match 検証前のローカルファイル::生成する(一時ファイル.パス()).検証する(要求.識別子(), 要求.バイト数()) {
            Ok(検証済み) => Ok(ダウンロード完了::生成する(検証済み)),
            Err(エラー) => {
                一時ファイルを可能な限り削除する(一時ファイル.パス());
                Err(エラー)
            }
        }
    }
}
