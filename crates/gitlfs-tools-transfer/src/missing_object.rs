//! 点検で「保管先から取り出せない」と判定した1オブジェクトと、その事由。
//!
//! 事由の判別共用体を同じファイルへ置くのは、これが`欠落オブジェクト`のフィールドの型で
//! あり、2つで1つの記述を成すためである。別ファイルへ分けると、どちらも単独では意味を
//! 持たない一片になる。

use gitlfs_tools_domain::{オブジェクト識別子, 期待バイト数};

/// 保管先から期待どおりに取り出せないオブジェクト。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 欠落オブジェクト {
    識別子: オブジェクト識別子,
    事由: 欠落の事由,
}

/// 取り出せない理由。実体が消えた場合と、実体は在るがバイト数が食い違う場合を区別する。
/// どちらも利用者が取る行動は「送り直す」で同じだが、後者は保管先で内容が壊れたことを
/// 示すため、表示で区別する。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 欠落の事由 {
    保管先に実体が無い,
    バイト数が食い違う { 保管先の実サイズ: 期待バイト数 },
}

impl 欠落オブジェクト {
    pub(crate) fn 生成する(識別子: オブジェクト識別子, 事由: 欠落の事由) -> Self {
        Self { 識別子, 事由 }
    }

    pub fn 識別子(&self) -> &オブジェクト識別子 {
        &self.識別子
    }

    pub fn 事由(&self) -> 欠落の事由 {
        self.事由
    }
}

impl std::fmt::Display for 欠落の事由 {
    fn fmt(&self, 出力先: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::保管先に実体が無い => write!(出力先, "保管先に実体がありません"),
            Self::バイト数が食い違う { 保管先の実サイズ } => {
                write!(出力先, "保管先の実体のバイト数が食い違います(保管先: {保管先の実サイズ})")
            }
        }
    }
}
