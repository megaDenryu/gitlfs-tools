//! 保管先のオブジェクト置き場を、ローカルファイルシステムで開くディレクトリとして表す値型。
//!
//! `保管先オブジェクトのローカルファイルパス`が1オブジェクトのファイルを表すのに対し、
//! この型はその親にあたる置き場（`<基底パス>/lfs/objects`）を表し、配下の走査を持つ。

use std::path::PathBuf;

use gitlfs_tools_domain::{保管エラー, 保管先オブジェクトパス};
use gitlfs_tools_storage_port::保管オブジェクト総数;

/// 保管先のオブジェクト置き場のローカルディレクトリ。
#[derive(Debug, Clone, PartialEq, Eq)]
#[repr(transparent)]
pub(crate) struct 保管先オブジェクト置き場のローカルディレクトリ(PathBuf);

impl 保管先オブジェクト置き場のローカルディレクトリ {
    pub(crate) fn 保管先オブジェクトパスから生成する(パス: &保管先オブジェクトパス) -> Self {
        Self(PathBuf::from(パス.文字列表現()))
    }

    /// 配下のファイルを再帰的に数える。置き場そのものが未作成の場合は0件として扱う
    /// （まだ1件もアップロードしていない状態であり、失敗ではない）。
    ///
    /// 注意: 深さの上限が識別子の階層（2文字ごとに2段）で決まっているため再帰でも足りるが、
    /// 走査するディレクトリを自前の積み上げで持ち、深さに依存しない形にしている。
    pub(crate) fn 配下のオブジェクトを数える(&self) -> Result<保管オブジェクト総数, 保管エラー> {
        if !self.0.exists() {
            return Ok(保管オブジェクト総数::生成する(0));
        }

        let mut 未走査のディレクトリ = vec![self.0.clone()];
        let mut 件数: u64 = 0;

        while let Some(ディレクトリ) = 未走査のディレクトリ.pop() {
            for 要素 in std::fs::read_dir(&ディレクトリ).map_err(読み取り失敗を保管エラーにする)? {
                let 要素 = 要素.map_err(読み取り失敗を保管エラーにする)?;
                let 種別 = 要素.file_type().map_err(読み取り失敗を保管エラーにする)?;
                if 種別.is_dir() {
                    未走査のディレクトリ.push(要素.path());
                } else {
                    件数 += 1;
                }
            }
        }

        Ok(保管オブジェクト総数::生成する(件数))
    }
}

fn 読み取り失敗を保管エラーにする(エラー: std::io::Error) -> 保管エラー {
    保管エラー::ローカル入出力 {
        説明: format!("保管先のオブジェクト置き場を走査できませんでした: {エラー}"),
    }
}
