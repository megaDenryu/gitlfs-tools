//! 値そのものが書かれた秘密の検出。
//!
//! キー名が文中に現れることと、そのキーへ値が代入されていることを区別する。文書が
//! 「この値は秘密であるためコミットしない」と説明するためにキー名を書く記述は秘密の
//! 混入ではないため検出しない。検出するのは、キー名の直後に代入の記号があり、その先へ
//! 秘密らしい長さの値が続く形と、秘密鍵ブロックの見出しの2つである。
//!
//! 注意: 探す綴りをこのファイルへ直接書くと、このファイル自身が追跡対象になった時点で
//! 検査が自分の探している綴りを自分の中に見つけて不合格になる。各綴りを断片へ分けて
//! 実行時にのみ結合するため、探している綴りはソースのどこにも連続した形で現れない。

const 秘密らしい値の最小文字数: usize = 8;

pub struct 秘密の値の検出器 {
    代入を探すキー名一覧: Vec<String>,
    そのまま探す見出し一覧: Vec<String>,
}

impl 秘密の値の検出器 {
    pub fn 既定() -> Self {
        Self {
            代入を探すキー名一覧: vec![
                クライアント認証の秘密情報を示すキー名を組み立てる(),
                認証更新用トークンを示すキー名を組み立てる(),
            ],
            そのまま探す見出し一覧: vec![秘密鍵ブロックの見出しを組み立てる()],
        }
    }

    pub fn 検出した記述を列挙する(&self, 内容: &str) -> Vec<String> {
        let mut 説明一覧 = Vec::new();
        for キー名 in &self.代入を探すキー名一覧 {
            if 値の代入を含むか(内容, キー名) {
                説明一覧.push(format!("\"{キー名}\"へ値が代入されている"));
            }
        }
        for 見出し in &self.そのまま探す見出し一覧 {
            if 内容.contains(見出し.as_str()) {
                説明一覧.push(format!("\"{見出し}\"を含む"));
            }
        }
        説明一覧
    }
}

fn 値の代入を含むか(内容: &str, キー名: &str) -> bool {
    let mut 走査開始位置 = 0;
    while let Some(相対位置) = 内容[走査開始位置..].find(キー名) {
        let キー名の直後 = 走査開始位置 + 相対位置 + キー名.len();
        if 秘密らしい値が代入されているか(&内容[キー名の直後..]) {
            return true;
        }
        走査開始位置 = キー名の直後;
    }
    false
}

fn 秘密らしい値が代入されているか(キー名より後ろ: &str) -> bool {
    let 記号以降 = キー名より後ろ.trim_start_matches([' ', '\t']);
    let Some(値の位置) = 記号以降.strip_prefix('=').or_else(|| 記号以降.strip_prefix(':')) else {
        return false;
    };
    let 値 = 値の位置.trim_start_matches([' ', '\t', '"', '\'']);
    let 値らしい文字数 = 値
        .chars()
        .take_while(|文字| 文字.is_ascii_alphanumeric() || matches!(文字, '-' | '_' | '.' | '~' | '+' | '/'))
        .count();
    値らしい文字数 >= 秘密らしい値の最小文字数
}

fn クライアント認証の秘密情報を示すキー名を組み立てる() -> String {
    ["client", "_secret"].concat()
}

fn 認証更新用トークンを示すキー名を組み立てる() -> String {
    ["refresh", "_token"].concat()
}

fn 秘密鍵ブロックの見出しを組み立てる() -> String {
    ["BEGIN PRIVATE", " KEY"].concat()
}
