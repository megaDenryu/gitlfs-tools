//! 実装の割り当てと文書の対応表を突き合わせ、食い違いを判定して報告する。
//!
//! 実装にあるのに文書へ載っていないコードと、文書にあるのに実装から消えたコードの
//! 両方を違反とする。後者を見るのは、行数の例外台帳の陳腐化検出と同じ理由である。
//! 片側だけを見ると、削除したコードの説明が文書に残り続けても誰も気づけない。

use crate::error_code_table::document_table::文書のエラーコード;
use crate::error_code_table::error_code_number::エラーコード番号;
use crate::error_code_table::implementation_source::実装のエラーコード;

pub enum 対応表違反 {
    文書に載っていない実装のコード { 番号: エラーコード番号, 名前: String },
    実装から消えた文書のコード { 番号: エラーコード番号, 意味: String },
}

pub fn 違反を判定する(実装一覧: &[実装のエラーコード], 文書一覧: &[文書のエラーコード]) -> Vec<対応表違反> {
    let mut 違反一覧 = Vec::new();

    for 実装 in 実装一覧 {
        if !文書一覧.iter().any(|文書| 文書.番号 == 実装.番号) {
            違反一覧.push(対応表違反::文書に載っていない実装のコード {
                番号: 実装.番号,
                名前: 実装.名前.clone(),
            });
        }
    }
    for 文書 in 文書一覧 {
        if !実装一覧.iter().any(|実装| 実装.番号 == 文書.番号) {
            違反一覧.push(対応表違反::実装から消えた文書のコード {
                番号: 文書.番号,
                意味: 文書.意味.clone(),
            });
        }
    }

    違反一覧.sort_by_key(番号を取り出す);
    違反一覧
}

pub fn 結果を報告する(実装件数: usize, 文書件数: usize, 違反一覧: &[対応表違反]) -> Result<(), String> {
    if !違反一覧.is_empty() {
        for 違反 in 違反一覧 {
            eprintln!("{}", 違反を文字列にする(違反));
        }
        return Err(format!("エラーコード対応表と実装の食い違いが{}件見つかった", 違反一覧.len()));
    }

    println!("実装のエラーコード{実装件数}件と、トラブルシューティング.mdの対応表{文書件数}件が一致した");
    Ok(())
}

fn 番号を取り出す(違反: &対応表違反) -> エラーコード番号 {
    match 違反 {
        対応表違反::文書に載っていない実装のコード { 番号, .. }
        | 対応表違反::実装から消えた文書のコード { 番号, .. } => *番号,
    }
}

fn 違反を文字列にする(違反: &対応表違反) -> String {
    match 違反 {
        対応表違反::文書に載っていない実装のコード { 番号, 名前 } => format!(
            "違反: 実装のエラーコード{番号}({名前})が、トラブルシューティング.mdの対応表に載っていない。表へ意味と対処を追記すること"
        ),
        対応表違反::実装から消えた文書のコード { 番号, 意味 } => format!(
            "違反: 対応表のコード{番号}「{意味}」に対応する割り当てが実装に無い。表から削除すること"
        ),
    }
}
