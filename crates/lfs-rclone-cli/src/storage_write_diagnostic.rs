//! `doctor`の追加診断4「保管先へ実際に書き込めるか」。`storage_reachability_diagnostic`は
//! 読み取り側（起動確認・基点の存在確認）だけであり、権限設定によっては「読めるが書けない」
//! 状態を見逃す。この診断は一時オブジェクトの領域へ実際に書き込み・読み戻し・削除を行う。
//! rclone子プロセス方式ではネットワークを使うため、他の診断より時間がかかりうる。
//!
//! 確認する事実（一時領域へ書けること）はどちらの方式でも同じであるため項目名は共通にし、
//! 確認の手段だけを方式で分ける。

use lfs_rclone_config::{PCプロファイル, 保管先の指定};
use lfs_rclone_local::ローカル保管先ルートディレクトリ;

use crate::diagnostic_finding::診断結果;
use crate::doctor_scratch_directory::書き込み確認用の作業領域;
use crate::local_storage_write_probe::ローカル保管先の書き込み確認;
use crate::storage_write_probe::{保管先書き込み確認, 書き込み確認結果};
use crate::timeout_process_runner::タイムアウト付きrclone実行器;

const 項目名: &str = "保管先への書き込み確認";

pub(crate) fn 診断する(プロファイル: Option<&PCプロファイル>) -> 診断結果 {
    let Some(プロファイル) = プロファイル else {
        return 診断結果::不足から生成する(項目名, &"プロファイルが解決できていません", "先に設定の不足を解消してください");
    };

    let 確認結果 = match プロファイル.保管先() {
        保管先の指定::Rclone子プロセス { リモート名, 実行ファイル, 転送タイムアウト } => {
            let 実行器 = タイムアウト付きrclone実行器::生成する(実行ファイル.clone(), *転送タイムアウト);
            保管先書き込み確認::生成する(実行器, リモート名.clone())
                .一時オブジェクトで確認する(プロファイル.基底パス(), &書き込み確認用の作業領域())
        }
        保管先の指定::ローカルディレクトリ { ルートディレクトリ } => {
            ローカル保管先の書き込み確認::生成する(ローカル保管先ルートディレクトリ::生成する(ルートディレクトリ.パス()))
                .一時オブジェクトで確認する(プロファイル.基底パス())
        }
    };

    match 確認結果 {
        Ok(書き込み確認結果::問題なし) => 診断結果::問題なし { 項目: 項目名 },
        Ok(書き込み確認結果::片付け残り { 説明 }) => 診断結果::注記あり { 項目: 項目名, 注記: 説明 },
        Err(エラー) => 診断結果::不足から生成する(項目名, &エラー, "保管先の権限設定・接続を確認してください"),
    }
}
