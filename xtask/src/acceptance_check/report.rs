//! 受入試験の結果を1項目ずつ標準出力へ書く。「9項目すべて成功」のような要約だけでは
//! 終わらせず、各項目の期待した結果と実際の結果を必ず出す（親からの指示）。

use crate::acceptance_check::check_result::{検査状態, 検査結果};

pub fn 結果を報告する(結果一覧: &[検査結果], 追加所見: &[String]) -> Result<(), String> {
    println!("== Issue #2 14節 v1受入条件 1〜9番の実証結果 ==");
    for 結果 in 結果一覧 {
        println!();
        println!("{}. {}", 結果.番号, 結果.表題);
        println!("  期待した結果: {}", 結果.期待した結果);
        match &結果.状態 {
            検査状態::合格 { 実際の結果 } => println!("  実際の結果  : [合格] {実際の結果}"),
            検査状態::不合格 { 実際の結果 } => println!("  実際の結果  : [不合格] {実際の結果}"),
            検査状態::未実施 { 理由 } => println!("  実際の結果  : [未実施] {理由}"),
        }
    }

    if !追加所見.is_empty() {
        println!();
        println!("== 追加所見 ==");
        for 所見 in 追加所見 {
            println!("- {所見}");
        }
    }

    let 不合格件数 = 結果一覧.iter().filter(|結果| !結果.合格したか()).count();
    println!();
    println!("== まとめ: {}項目中{}項目が合格 ==", 結果一覧.len(), 結果一覧.len() - 不合格件数);

    if 不合格件数 == 0 { Ok(()) } else { Err(format!("{不合格件数}項目が不合格または未実施だった")) }
}
