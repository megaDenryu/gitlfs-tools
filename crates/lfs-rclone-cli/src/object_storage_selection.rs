//! PC設定が選んだ保管先の実装を1つの型として表す判別共用体。
//!
//! `資産転送サービス`は保管庫の型引数を1つだけ取るため、方式ごとに別のサービス型・別の
//! セッション型を並べるのではなく、この型が`オブジェクト保管庫`として振る舞い、選ばれた
//! 実装へ委譲する。方式を足したときに委譲の追加漏れへコンパイルエラーで気づける。
//!
//! 起動確認も方式ごとに意味が違うため、この型のメソッドとして持つ。確認に要る値
//! （rcloneの実行ファイルの場所・ローカル保管先の基点）は保管庫の実装が外へ見せないため、
//! 組み立てのときに受け取ってここで保持する。

use lfs_rclone_domain::{
    一時ファイルパス, オブジェクト状態, オブジェクト識別子, 保管エラー, 期待バイト数, Rclone実行ファイルの場所, 検証済みローカルファイル,
};
use lfs_rclone_local::{ローカルディレクトリ保管庫, ローカル保管先ルートディレクトリ};
use lfs_rclone_protocol::初期化エラー;
use lfs_rclone_rclone::Rclone保管庫;
use lfs_rclone_storage_port::{アップロード結果, オブジェクト保管庫, 保管オブジェクト総数};

use crate::rclone_startup_check::{rclone実行ファイルの起動可否を確かめる, rcloneの起動を確認する};

pub(crate) enum 選択された保管庫 {
    Rclone子プロセス { 保管庫: Rclone保管庫, 実行ファイル: Rclone実行ファイルの場所 },
    ローカルディレクトリ { 保管庫: ローカルディレクトリ保管庫, ルートディレクトリ: ローカル保管先ルートディレクトリ },
}

impl 選択された保管庫 {
    /// この方式に意味のある起動確認を行う。
    ///
    /// rcloneの子プロセス方式では、実行ファイルを起動できるかを先に確かめ、それが通って
    /// からリモートへの疎通を確かめる。順序を入れ替えると、rcloneが導入されていないPCで
    /// 「認証情報を確認してください」と誤診断する（`rclone_startup_check.rs`の注意書き）。
    ///
    /// ローカルディレクトリ方式では子プロセスを起動しないため、rcloneの起動確認は行わない。
    /// 代わりに保管先の基点が実在するかを確かめる（マウントされていないドライブを指したまま
    /// 転送を始めると、実体がどこへ落ちたのか利用者に分からなくなる）。
    pub(crate) fn 保管先が使える状態にあることを確かめる(&self) -> Result<(), 初期化エラー> {
        match self {
            Self::Rclone子プロセス { 保管庫, 実行ファイル } => {
                rclone実行ファイルの起動可否を確かめる(実行ファイル)?;
                rcloneの起動を確認する(保管庫).map_err(初期化エラー::保管失敗)
            }
            Self::ローカルディレクトリ { ルートディレクトリ, .. } => {
                ルートディレクトリ.実在を確かめる().map_err(初期化エラー::保管失敗)
            }
        }
    }
}

impl オブジェクト保管庫 for 選択された保管庫 {
    fn 存在を確認する(&self, 識別子: &オブジェクト識別子, 期待バイト数: 期待バイト数) -> Result<オブジェクト状態, 保管エラー> {
        match self {
            Self::Rclone子プロセス { 保管庫, .. } => 保管庫.存在を確認する(識別子, 期待バイト数),
            Self::ローカルディレクトリ { 保管庫, .. } => 保管庫.存在を確認する(識別子, 期待バイト数),
        }
    }

    fn 保管しているオブジェクトの総数を数える(&self) -> Result<保管オブジェクト総数, 保管エラー> {
        match self {
            Self::Rclone子プロセス { 保管庫, .. } => 保管庫.保管しているオブジェクトの総数を数える(),
            Self::ローカルディレクトリ { 保管庫, .. } => 保管庫.保管しているオブジェクトの総数を数える(),
        }
    }

    fn アップロードする(&self, 識別子: &オブジェクト識別子, 転送元: &検証済みローカルファイル) -> Result<アップロード結果, 保管エラー> {
        match self {
            Self::Rclone子プロセス { 保管庫, .. } => 保管庫.アップロードする(識別子, 転送元),
            Self::ローカルディレクトリ { 保管庫, .. } => 保管庫.アップロードする(識別子, 転送元),
        }
    }

    fn ダウンロードする(&self, 識別子: &オブジェクト識別子, 期待バイト数: 期待バイト数, 保存先: &一時ファイルパス) -> Result<(), 保管エラー> {
        match self {
            Self::Rclone子プロセス { 保管庫, .. } => 保管庫.ダウンロードする(識別子, 期待バイト数, 保存先),
            Self::ローカルディレクトリ { 保管庫, .. } => 保管庫.ダウンロードする(識別子, 期待バイト数, 保存先),
        }
    }
}
