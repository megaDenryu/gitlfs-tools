//! 読み込みは受け付けるが、agentがもう使わないPC設定の項目。
//!
//! 値ではなく「キーが残っている」という事実だけを運ぶ。値を保持すると、使わないはずの
//! 設定値を後から参照する経路が残り、廃止が形だけになるためである。

/// PC設定に書けるが、agentがもう読まない項目。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 使われなくなった設定項目 {
    一時ディレクトリの指定,
}

impl 使われなくなった設定項目 {
    /// PC設定ファイルに現れるキーの綴り。外部仕様（TOMLのkey）であるため英語のまま保つ。
    pub fn キー名(self) -> &'static str {
        match self {
            Self::一時ディレクトリの指定 => "temp_directory",
        }
    }

    /// 利用者へそのまま見せる、使われなくなった経緯の説明。
    pub fn 使われなくなった経緯(self) -> &'static str {
        match self {
            Self::一時ディレクトリの指定 => {
                "ダウンロードの一時ファイルはGit LFSがrenameで奪うため、リポジトリと同じボリュームに置く必要がある。\
                 置き場所をリポジトリ内(Gitディレクトリの下のlfs/tmp)へ固定したため、この項目は読まなくなった"
            }
        }
    }
}
