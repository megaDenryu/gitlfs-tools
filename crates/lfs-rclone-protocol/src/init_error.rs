//! `init`要求の処理全体（プロジェクト設定・PC設定・プロファイル解決・rclone起動確認・
//! 一時保存先の作成）で起こりうる失敗の分類。分類の判定自体はコンポジションルート
//! （`lfs-rclone-cli`）が行う。このcrateは`lfs-rclone-config`・`lfs-rclone-rclone`へ
//! 依存できないため（判断2「プロトコルアダプタは保管庫の実装を知らない」）、判定済みの
//! 結果だけをここで受け取る。
//!
//! 各バリアントの`説明`は変換元エラーの`Display`（秘密情報を含まない）をそのまま複製した
//! ものであり、新たな秘密漏洩経路を作らない（CLAUDE.md「認証情報を混入させない」）。

use lfs_rclone_domain::保管エラー;

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum 初期化エラー {
    #[error("プロジェクト設定が見つかりません: {説明}")]
    プロジェクト設定未検出 { 説明: String },

    #[error("PC設定が見つかりません: {説明}")]
    PC設定未検出 { 説明: String },

    #[error("PC設定ディレクトリを特定できません: {説明}")]
    PC設定ディレクトリ不明 { 説明: String },

    #[error("設定の解析に失敗しました: {説明}")]
    設定解析失敗 { 説明: String },

    #[error("設定のスキーマ版が対応していません: {説明}")]
    未対応スキーマ版 { 説明: String },

    #[error("論理プロファイルが未定義です: {説明}")]
    未定義プロファイル { 説明: String },

    #[error("設定の読み込みに失敗しました: {説明}")]
    設定読み込み入出力失敗 { 説明: String },

    #[error("rclone実行ファイルが見つかりません: {説明}")]
    Rclone実行ファイル不在 { 説明: String },

    #[error("rcloneの起動確認に失敗しました: {0}")]
    保管失敗(保管エラー),
}
