//! `release`が実際にタグを発行するのか、何をするかの表示だけで終えるのかの区別。

/// `release`が最後に何をするかの選択。
pub enum タグ発行の仕方 {
    下見だけ,
    実際に発行する,
}

impl タグ発行の仕方 {
    pub fn 起動引数から解釈する(引数: &[String]) -> Result<Self, String> {
        match 引数 {
            [] => Ok(Self::実際に発行する),
            [単一] if 単一 == "--dry-run" => Ok(Self::下見だけ),
            [先頭, ..] => Err(format!("releaseが解釈できない引数: {先頭}。指定できるのは--dry-runだけである")),
        }
    }

    /// 前提を満たしていなくても残りの確認を続けるか。下見は「発行までに何が足りないか」を
    /// 一度で全部見せるために続ける。実際の発行は、最初に見つけた不足の時点で中止する。
    pub fn 満たしていない前提があっても続けるか(&self) -> bool {
        matches!(self, Self::下見だけ)
    }
}
