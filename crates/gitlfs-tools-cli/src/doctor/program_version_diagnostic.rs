//! `doctor`の出力の先頭に置く、この実行ファイルの版の表示。
//!
//! この項目は合否を判定しない。版が古いか新しいかを機械が決められないためである。
//! 2台のPCが同じ版を使っているかどうかは利用者が見比べて判断する。判定しない項目は
//! `診断結果::参考情報`として`[情報]`の行で出し、`[OK]`と紛れないようにする。
//!
//! 先頭に置く理由は、利用者が2台のPCの`doctor`の出力を並べたときに、最初の1行だけで
//! 版の一致を確かめられるようにするためである。

use crate::doctor::finding::診断結果;
use crate::program_version::この実行ファイルの版;

const 項目名: &str = "gitlfs-tools の版";

pub(crate) fn この実行ファイルの版を診断する() -> 診断結果 {
    let 版 = この実行ファイルの版::cargoのパッケージ版から生成する();
    診断結果::参考情報 { 項目: 項目名, 内容: 版.版の文字列().to_owned() }
}
