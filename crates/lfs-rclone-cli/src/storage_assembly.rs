//! PC設定が選んだ方式の保管庫を組み立てる。
//! `転送セッション初期化境界::開始する`と`check-objects`・`doctor`から呼ばれる私有ヘルパーで
//! ある（グローバルCLAUDE.md「サービスの依存保持とコールバックの限定」条1: 親のサービス型が
//! 依存を保持した上での工程ヘルパー）。
//!
//! 組み立ての綴りはこのファイルの1箇所だけに置く。方式ごとの起動確認は
//! `選択された保管庫::保管先が使える状態にあることを確かめる`が持つため、起動確認の有無で
//! 組み立てを2通り書き分けない（保管先の方式を増やしたときに片方だけ直す事故を防ぐ）。

use lfs_rclone_config::{PCプロファイル, 保管先の指定};
use lfs_rclone_local::{ローカルディレクトリ保管庫, ローカル保管先ルートディレクトリ};
use lfs_rclone_protocol::初期化エラー;
use lfs_rclone_rclone::Rclone保管庫;

use crate::object_storage_selection::選択された保管庫;

/// 起動確認を行わずに保管庫だけを組み立てる。`doctor`の保管先オブジェクト数の表示に使う。
/// `doctor`は同じ実行の中で保管先への到達確認と書き込み確認を別項目として済ませており、
/// ここで同じ確認を繰り返すと、rclone子プロセス方式で無駄な起動が増える。
pub(crate) fn 起動確認を伴わずに保管庫を組み立てる(プロファイル: &PCプロファイル) -> 選択された保管庫 {
    match プロファイル.保管先() {
        保管先の指定::Rclone子プロセス { リモート名, 実行ファイル, 転送タイムアウト } => 選択された保管庫::Rclone子プロセス {
            保管庫: Rclone保管庫::生成する(
                実行ファイル.clone(),
                リモート名.clone(),
                プロファイル.基底パス().clone(),
                *転送タイムアウト,
            ),
            実行ファイル: 実行ファイル.clone(),
        },
        保管先の指定::ローカルディレクトリ { ルートディレクトリ } => {
            let ルート = ローカル保管先ルートディレクトリ::生成する(ルートディレクトリ.パス());
            選択された保管庫::ローカルディレクトリ {
                保管庫: ローカルディレクトリ保管庫::生成する(ルート.clone(), プロファイル.基底パス().clone()),
                ルートディレクトリ: ルート,
            }
        }
    }
}

pub(crate) fn 起動確認を済ませた保管庫を組み立てる(プロファイル: &PCプロファイル) -> Result<選択された保管庫, 初期化エラー> {
    let 保管庫 = 起動確認を伴わずに保管庫を組み立てる(プロファイル);
    保管庫.保管先が使える状態にあることを確かめる()?;
    Ok(保管庫)
}
