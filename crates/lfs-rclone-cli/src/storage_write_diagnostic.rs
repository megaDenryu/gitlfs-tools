//! `doctor`の追加診断4「保管先へ実際に書き込めるか」。既存の`rclone起動を診断する`は
//! 読み取り（存在確認）だけであり、Google Driveの権限設定によっては「読めるが書けない」
//! 状態を見逃す。この診断は一時オブジェクトの領域へ実際に書き込み・読み戻し・削除を行う。
//! ネットワークを使うため、他の診断より時間がかかりうる。

use lfs_rclone_config::PCプロファイル;

use crate::diagnostic_finding::診断結果;
use crate::storage_write_probe::{保管先書き込み確認, 書き込み確認結果};
use crate::timeout_process_runner::タイムアウト付きrclone実行器;

const 項目名: &str = "保管先への書き込み確認";

pub(crate) fn 診断する(プロファイル: Option<&PCプロファイル>) -> 診断結果 {
    let Some(プロファイル) = プロファイル else {
        return 診断結果::不足から生成する(項目名, &"プロファイルが解決できていません", "先に設定の不足を解消してください");
    };

    let 実行器 = タイムアウト付きrclone実行器::生成する(プロファイル.rclone実行ファイル().clone(), プロファイル.転送タイムアウト());
    let 確認 = 保管先書き込み確認::生成する(実行器, プロファイル.rcloneリモート().clone());

    match 確認.一時オブジェクトで確認する(プロファイル.基底パス(), プロファイル.一時ディレクトリ()) {
        Ok(書き込み確認結果::問題なし) => 診断結果::問題なし { 項目: 項目名 },
        Ok(書き込み確認結果::片付け残り { 説明 }) => 診断結果::注記あり { 項目: 項目名, 注記: 説明 },
        Err(エラー) => 診断結果::不足から生成する(項目名, &エラー, "保管先の権限設定・接続を確認してください"),
    }
}
