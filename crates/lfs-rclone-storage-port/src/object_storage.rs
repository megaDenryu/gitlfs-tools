//! 保管境界のトレイト定義。

use lfs_rclone_domain::{
    オブジェクト状態, オブジェクト識別子, 一時ファイルパス, 保管エラー, 期待バイト数, 検証済み転送元,
};

use crate::upload_result::アップロード結果;

/// 保管先（rcloneのリモート）へのオブジェクトの保存・取得を抽象化する境界。
/// 実装（rclone子プロセス起動等）は`lfs-rclone-rclone`が持つ（アーキテクチャ.md 2節）。
pub trait オブジェクト保管庫 {
    /// 最終保存先でのオブジェクトの存在とバイト数を確認する。
    fn 存在を確認する(&self, 識別子: &オブジェクト識別子, 期待バイト数: 期待バイト数) -> Result<オブジェクト状態, 保管エラー>;

    /// 検証済みのローカル入力を最終保存先へ置く。同じ内容が既に存在する場合は転送しない
    /// （判断5「保管先のオブジェクトは変更不能として扱う」）。
    fn アップロードする(&self, 識別子: &オブジェクト識別子, 転送元: &検証済み転送元) -> Result<アップロード結果, 保管エラー>;

    /// 最終保存先のオブジェクトを、呼び出し側が用意した一時ファイルパスへ取得する。
    /// 既存の内容を無言で上書きしない（Issue #2 4節）。
    fn ダウンロードする(
        &self,
        識別子: &オブジェクト識別子,
        期待バイト数: 期待バイト数,
        保存先: &一時ファイルパス,
    ) -> Result<(), 保管エラー>;
}
