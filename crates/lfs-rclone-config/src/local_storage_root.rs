//! PC設定の`base_path`を、ローカルファイルシステム上の保管先の基点として解釈した値型。
//!
//! `storage = "local"`のときだけ意味を持つ。`保管先基底パス`（domain層）は`/`区切りの綴りを
//! 知る値型であり生の文字列アクセサを持たないため、実在確認とファイル操作に使う形として
//! この型を別に持つ。実在するかどうかの確認はこの層では行わない（この層はファイルシステムの
//! 状態を見ない。確認は保管庫の実装とコンポジションルートが行う）。

use std::path::{Path, PathBuf};

/// ローカルファイルシステム上の保管先の基点。マウント済みのドライブの中を指す想定である。
#[derive(Debug, Clone, PartialEq, Eq)]
#[repr(transparent)]
pub struct ローカルファイルシステム上の保管先ルート(PathBuf);

impl ローカルファイルシステム上の保管先ルート {
    pub(crate) fn 生成する(パス: impl Into<PathBuf>) -> Self {
        Self(パス.into())
    }

    /// 保管庫の実装へ基点を引き渡すための参照（境界1箇所）。
    pub fn パス(&self) -> &Path {
        &self.0
    }
}
