//! 点検の対象となる1オブジェクトを表す値型。

use lfs_rclone_domain::{オブジェクト識別子, 期待バイト数};

/// 保管先に在るかを点検する1オブジェクト。Git LFSが参照している識別子とバイト数の組であり、
/// どのファイルの実体かという作業ツリー上の位置は含まない（この層はGitを知らない）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 点検対象オブジェクト {
    識別子: オブジェクト識別子,
    バイト数: 期待バイト数,
}

impl 点検対象オブジェクト {
    /// 検証済みの識別子とバイト数から組み立てる。生の文字列からの検証は呼び出し側
    /// （Gitの出力を読む層）が済ませており、この層で二度行わない。
    pub fn 生成する(識別子: オブジェクト識別子, バイト数: 期待バイト数) -> Self {
        Self { 識別子, バイト数 }
    }

    pub fn 識別子(&self) -> &オブジェクト識別子 {
        &self.識別子
    }

    pub fn バイト数(&self) -> 期待バイト数 {
        self.バイト数
    }
}
