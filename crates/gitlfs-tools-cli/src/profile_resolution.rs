//! プロジェクト設定の探索と読み込み、PC設定の読み込み、論理プロファイル名の解決という3段を
//! 1箇所へまとめる。コンポジションルートの「設定の読み込み」役割のファイルである
//! （コード分割規約.md 1節）。
//!
//! この3段は`init`（`transfer_init_boundary`）と`check-objects`（`check_objects_command`）が
//! 同じ順序で必要とする。段の順序と読み込む対象をここへ閉じ、呼び出し側は返った`設定エラー`を
//! 自分の文脈のエラー型へ変換するだけにする。
//!
//! `doctor`の`config_diagnostic`は同じ3段を含むが、各段の成否を個別の診断項目として報告する
//! ことが目的であり、途中で失敗しても残りの段を続ける。まとめる対象にしない。

use std::path::{Path, PathBuf};

use gitlfs_tools_config::{PC設定の場所, PCプロファイル, プロジェクト設定の場所, 設定エラー};

/// プロジェクト設定を探し始めるディレクトリと、PC設定ファイルの置き場所の2つを保持する。
pub(crate) struct プロファイル解決に使う設定の置き場所 {
    プロジェクト設定の探索起点: PathBuf,
    pc設定の場所: PC設定の場所,
}

impl プロファイル解決に使う設定の置き場所 {
    pub(crate) fn 生成する(プロジェクト設定の探索起点: impl Into<PathBuf>, pc設定の場所: PC設定の場所) -> Self {
        Self { プロジェクト設定の探索起点: プロジェクト設定の探索起点.into(), pc設定の場所 }
    }

    pub(crate) fn 探索起点(&self) -> &Path {
        &self.プロジェクト設定の探索起点
    }

    /// プロジェクト設定が書いた論理プロファイル名を、PC設定が持つ実際のプロファイルへ解決する。
    pub(crate) fn 論理プロファイルを解決する(&self) -> Result<PCプロファイル, 設定エラー> {
        let プロジェクト設定 =
            プロジェクト設定の場所::探索する(&self.プロジェクト設定の探索起点).and_then(|場所| 場所.読み込む())?;
        let pc設定 = self.pc設定の場所.読み込む()?;
        pc設定.プロファイルを解決する(プロジェクト設定.プロファイル()).cloned()
    }
}
