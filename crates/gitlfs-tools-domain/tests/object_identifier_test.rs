//! `オブジェクト識別子`の解析・検証のテスト。

use gitlfs_tools_domain::オブジェクト識別子;

/// 16進16文字("0123456789abcdef")を4回繰り返した、正確に64文字の妥当な識別子。
/// 手打ちの64文字リテラルは文字数を誤りやすいため、繰り返しで構成する。
fn 妥当な識別子() -> String {
    "0123456789abcdef".repeat(4)
}

#[test]
fn 六十四文字の小文字十六進文字列は受理される() {
    assert!(オブジェクト識別子::生成する(&妥当な識別子()).is_ok());
}

#[test]
fn 六十三文字は拒否される() {
    let 識別子 = 妥当な識別子();
    let 短い文字列 = &識別子[..63];
    assert!(オブジェクト識別子::生成する(短い文字列).is_err());
}

#[test]
fn 六十五文字は拒否される() {
    let 長い文字列 = format!("{}0", 妥当な識別子());
    assert!(オブジェクト識別子::生成する(&長い文字列).is_err());
}

#[test]
fn 大文字を含む文字列は拒否される() {
    let 大文字混じり = 妥当な識別子().replace('a', "A");
    assert!(オブジェクト識別子::生成する(&大文字混じり).is_err());
}

#[test]
fn 十六進以外の文字を含む文字列は拒否される() {
    let 不正文字混じり = 妥当な識別子().replacen('0', "g", 1);
    assert!(オブジェクト識別子::生成する(&不正文字混じり).is_err());
}

#[test]
fn 空文字列は拒否される() {
    assert!(オブジェクト識別子::生成する("").is_err());
}
