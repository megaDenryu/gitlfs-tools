//! `git`の子プロセスをどのディレクトリで動かすかを表す判別共用体。
//!
//! 起動場所を`Option<PathBuf>`のような形で持つと「指定なし」と「たまたま空のパス」を
//! 区別できないため、現在地のままか指定ディレクトリかを判別共用体で表す
//! （グローバルCLAUDE.md「不在・未設定・使用不可」状態の設計）。`clone`サブコマンドは
//! 複製した先のリポジトリに対して`git`を動かすため、この指定を必要とする。

use std::path::PathBuf;
use std::process::Command;

use crate::work_tree_root::作業ツリールート;

pub(crate) enum Gitコマンドの実行場所 {
    現在地,
    指定ディレクトリ(PathBuf),
}

impl Gitコマンドの実行場所 {
    /// 作業ツリーのルートを`git`の実行場所にする。ディレクトリを裸のパスで受けず、
    /// どこを指しているかが型で分かる形にする（グローバルCLAUDE.md「プリミティブ執着禁止は
    /// パス・テキスト・名前にも適用する」）。
    pub(crate) fn 作業ツリールートから生成する(ルート: &作業ツリールート) -> Self {
        Self::指定ディレクトリ(ルート.パス().to_path_buf())
    }

    /// 組み立て途中の`git`コマンドへ実行場所を反映する。現在地の場合は何もせず、
    /// 呼び出し元プロセスの作業ディレクトリをそのまま継がせる。
    pub(crate) fn コマンドへ適用する(&self, コマンド: &mut Command) {
        if let Self::指定ディレクトリ(ディレクトリ) = self {
            コマンド.current_dir(ディレクトリ);
        }
    }
}
