//! `doctor`が保管先へ到達できるかを検査する。何をもって到達可能とするかは方式で違うため、
//! 項目名と対処の文言も方式ごとに変える。
//!
//! - rclone子プロセス方式: rclone実行ファイルを起動できるか。
//! - ローカルディレクトリ方式: 保管先の基点が実在するディレクトリか。子プロセスを起動
//!   しないため、rcloneの起動確認は意味を持たない。

use gitlfs_tools_config::{PCプロファイル, 保管先の指定};
use gitlfs_tools_local::ローカル保管先ルートディレクトリ;

use crate::doctor::finding::診断結果;
use crate::rclone_startup_check::rclone実行ファイルの起動可否を確かめる;

const 方式が未確定のときの項目名: &str = "保管先への到達確認";
const RCLONE子プロセス方式の項目名: &str = "rcloneの起動確認";
const ローカルディレクトリ方式の項目名: &str = "保管先ルートディレクトリの存在確認";

pub(crate) fn 保管先への到達を診断する(プロファイル: Option<&PCプロファイル>) -> 診断結果 {
    let Some(プロファイル) = プロファイル else {
        return 診断結果::不足から生成する(方式が未確定のときの項目名, &"プロファイルが解決できていません", "先に設定の不足を解消してください");
    };

    match プロファイル.保管先() {
        保管先の指定::Rclone子プロセス { 実行ファイル, .. } => match rclone実行ファイルの起動可否を確かめる(実行ファイル) {
            Ok(()) => 診断結果::問題なし { 項目: RCLONE子プロセス方式の項目名 },
            Err(エラー) => 診断結果::不足から生成する(
                RCLONE子プロセス方式の項目名,
                &エラー,
                "rcloneを導入するか、PC設定のrclone_executableでパスを明示してください",
            ),
        },
        保管先の指定::ローカルディレクトリ { ルートディレクトリ } => {
            match ローカル保管先ルートディレクトリ::生成する(ルートディレクトリ.パス()).実在を確かめる() {
                Ok(()) => 診断結果::問題なし { 項目: ローカルディレクトリ方式の項目名 },
                Err(エラー) => 診断結果::不足から生成する(
                    ローカルディレクトリ方式の項目名,
                    &エラー,
                    "PC設定のbase_pathが指すディレクトリを作るか、保管先のドライブをマウントしてください",
                ),
            }
        }
    }
}
