//! `doctor`が「PC設定にagentがもう読まない項目が残っていないか」を報告する。
//!
//! 残っていても転送は動くため不足としては扱わず、注記として消してよいことを伝える。
//! 黙って無視すると、利用者は設定した置き場所が今も効いていると誤解し続ける。

use lfs_rclone_config::PCプロファイル;

use crate::diagnostic_finding::診断結果;

const 項目名: &str = "PC設定に使われなくなった項目が残っていないか";

pub(crate) fn 使われなくなった設定項目の残存を診断する(プロファイル: Option<&PCプロファイル>) -> 診断結果 {
    let Some(プロファイル) = プロファイル else {
        return 診断結果::不足から生成する(項目名, &"プロファイルが解決できていません", "先に設定の不足を解消してください");
    };

    let 注記一覧: Vec<String> = プロファイル
        .使われなくなった項目一覧()
        .iter()
        .map(|項目| format!("{}は読まれていません。削除してください({})", 項目.キー名(), 項目.使われなくなった経緯()))
        .collect();

    if 注記一覧.is_empty() {
        診断結果::問題なし { 項目: 項目名 }
    } else {
        診断結果::注記あり { 項目: 項目名, 注記: 注記一覧.join(" / ") }
    }
}
