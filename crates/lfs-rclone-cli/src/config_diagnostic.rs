//! `doctor`がプロジェクト設定・PC設定・プロファイル解決を検査する。3つを1ファイルへ
//! まとめるのは、プロファイル解決がプロジェクト設定とPC設定の両方の読み込み成功に
//! 依存し、3つの合否が1つの検査手続きの内部で順に決まる単一の流れであるためである。

use std::path::Path;

use lfs_rclone_config::{PC設定, PC設定の場所, PCプロファイル, プロジェクト設定, プロジェクト設定の場所};

use crate::diagnostic_finding::診断結果;

const プロジェクト設定項目名: &str = "プロジェクト設定(.large-assets.toml)";
const PC設定項目名: &str = "PC設定";
const プロファイル項目名: &str = "論理プロファイルの解決";

/// 3件の診断結果と、後続の検査（rclone起動確認・一時ディレクトリ作成確認）が使う
/// 解決済みプロファイルをまとめて返す（裸のタプルを戻り値に出さない）。
pub(crate) struct 設定診断結果 {
    pub(crate) 結果一覧: Vec<診断結果>,
    pub(crate) プロファイル: Option<PCプロファイル>,
}

pub(crate) fn 診断する(起点: &Path, pc設定の場所: &PC設定の場所) -> 設定診断結果 {
    let mut 結果一覧 = Vec::new();

    let プロジェクト設定 = match プロジェクト設定の場所::探索する(起点).and_then(|場所| 場所.読み込む()) {
        Ok(設定) => {
            結果一覧.push(診断結果::問題なし { 項目: プロジェクト設定項目名 });
            Some(設定)
        }
        Err(エラー) => {
            結果一覧.push(診断結果::不足から生成する(プロジェクト設定項目名, &エラー, "init-projectで雛形を作成してください"));
            None
        }
    };

    let pc設定 = match pc設定の場所.読み込む() {
        Ok(設定) => {
            結果一覧.push(診断結果::問題なし { 項目: PC設定項目名 });
            Some(設定)
        }
        Err(エラー) => {
            結果一覧.push(診断結果::不足から生成する(PC設定項目名, &エラー, "導入手順に従ってPC設定を作成してください"));
            None
        }
    };

    let プロファイル = match プロジェクト設定.as_ref().zip(pc設定.as_ref()) {
        Some((プロジェクト, pc)) => {
            let (結果, プロファイル) = プロファイル解決を診断する(プロジェクト, pc);
            結果一覧.push(結果);
            プロファイル
        }
        None => None,
    };

    設定診断結果 { 結果一覧, プロファイル }
}

/// プロジェクト設定とPC設定の両方が読み込めた場合だけ呼ばれる純粋な判定。副作用を持たず、
/// 呼び出し側が結果を`結果一覧`へ積むかどうかを決める（無名クロージャで`Vec`を可変捕捉
/// しない。グローバルCLAUDE.md「サービスの依存保持とコールバックの限定」条3）。
fn プロファイル解決を診断する(プロジェクト設定: &プロジェクト設定, pc設定: &PC設定) -> (診断結果, Option<PCプロファイル>) {
    match pc設定.プロファイルを解決する(プロジェクト設定.プロファイル()) {
        Ok(プロファイル) => (診断結果::問題なし { 項目: プロファイル項目名 }, Some(プロファイル.clone())),
        Err(エラー) => (診断結果::不足から生成する(プロファイル項目名, &エラー, "PC設定へ該当プロファイルを追加してください"), None),
    }
}
