//! `git lfs ls-files`が挙げた1件のファイルを表す値型。

use lfs_rclone_domain::{オブジェクト識別子, 整合性エラー, 期待バイト数};
use lfs_rclone_transfer::点検対象オブジェクト;

/// Git LFSが実体を管理している作業ツリー上の1ファイル。点検の出力で「どのファイルの実体が
/// 欠けたか」を利用者へ示すために、識別子だけでなく作業ツリー内のパスも保持する。
pub(crate) struct GitLFS追跡ファイル {
    作業ツリー内のパス: String,
    識別子: オブジェクト識別子,
    バイト数: 期待バイト数,
}

impl GitLFS追跡ファイル {
    /// `git lfs ls-files --json`が返した1件から組み立てる。識別子が64文字の小文字16進
    /// 文字列でなければ`整合性エラー`を返す。
    pub(crate) fn 生成する(作業ツリー内のパス: String, 識別子文字列: &str, バイト数: u64) -> Result<Self, 整合性エラー> {
        Ok(Self {
            作業ツリー内のパス,
            識別子: オブジェクト識別子::生成する(識別子文字列)?,
            バイト数: 期待バイト数::生成する(バイト数),
        })
    }

    pub(crate) fn パス(&self) -> &str {
        &self.作業ツリー内のパス
    }

    pub(crate) fn 識別子(&self) -> &オブジェクト識別子 {
        &self.識別子
    }

    /// 点検サービスへ渡す形へ変換する。作業ツリー内のパスは転送層が知る必要のない情報で
    /// あるため、変換先には含まれない。
    pub(crate) fn 点検対象オブジェクトへ変換する(&self) -> 点検対象オブジェクト {
        点検対象オブジェクト::生成する(self.識別子.clone(), self.バイト数)
    }
}
