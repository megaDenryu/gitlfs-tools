//! `lfs-rclone-config`の`設定エラー`を、`lfs-rclone-protocol`が公開する`初期化エラー`へ
//! 変換する。`lfs-rclone-protocol`は`lfs-rclone-config`を知らないため
//! （アーキテクチャ.md 判断2）、この変換はコンポジションルート（このcrate）が持つ。

use lfs_rclone_config::設定エラー;
use lfs_rclone_protocol::初期化エラー;

pub(crate) fn 設定エラーへ変換する(エラー: 設定エラー) -> 初期化エラー {
    let 説明 = エラー.to_string();
    match エラー {
        設定エラー::プロジェクト設定未検出 => 初期化エラー::プロジェクト設定未検出 { 説明 },
        設定エラー::PC設定未検出 => 初期化エラー::PC設定未検出 { 説明 },
        設定エラー::PC設定ディレクトリ不明 => 初期化エラー::PC設定ディレクトリ不明 { 説明 },
        設定エラー::解析失敗 { .. } => 初期化エラー::設定解析失敗 { 説明 },
        設定エラー::未対応スキーマ版 { .. } => 初期化エラー::未対応スキーマ版 { 説明 },
        設定エラー::未定義プロファイル { .. } => 初期化エラー::未定義プロファイル { 説明 },
        設定エラー::ローカル入出力 { .. } => 初期化エラー::設定読み込み入出力失敗 { 説明 },
    }
}
