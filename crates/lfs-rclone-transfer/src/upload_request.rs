//! アップロード要求を表す値型。

use lfs_rclone_domain::{オブジェクト識別子, 保管エラー, 整合性エラー, 期待バイト数, 検証前のローカルファイル, 検証済みローカルファイル};

/// アップロードの要求。識別子とバイト数はここで検証し終える
/// （Issue #6 upload節1「識別子とバイト数を検証する」）。
pub struct アップロード要求 {
    識別子: オブジェクト識別子,
    バイト数: 期待バイト数,
    入力ファイル: 検証前のローカルファイル,
}

impl アップロード要求 {
    /// Git LFSから受け取る生の識別子文字列とバイト数から要求を組み立てる。
    /// 識別子が64文字の小文字16進文字列でなければ`整合性エラー`を返す。
    pub fn 生成する(識別子文字列: &str, バイト数: u64, 入力ファイル: 検証前のローカルファイル) -> Result<Self, 整合性エラー> {
        Ok(Self {
            識別子: オブジェクト識別子::生成する(識別子文字列)?,
            バイト数: 期待バイト数::生成する(バイト数),
            入力ファイル,
        })
    }

    pub fn 識別子(&self) -> &オブジェクト識別子 {
        &self.識別子
    }

    pub fn バイト数(&self) -> 期待バイト数 {
        self.バイト数
    }

    /// 入力ファイルの実測値を識別子・バイト数と照合し、`検証済みローカルファイル`へ昇格させる
    /// （Issue #6 upload節2「入力pathのsize/SHA-256を検証し、検証済みローカルファイルへ昇格させる」）。
    pub(crate) fn 転送元を検証する(self) -> Result<検証済みローカルファイル, 保管エラー> {
        let アップロード要求 { 識別子, バイト数, 入力ファイル } = self;
        入力ファイル.検証する(&識別子, バイト数)
    }
}
