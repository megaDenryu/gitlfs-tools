//! 保管先の基点がローカルファイルシステム上のどのディレクトリなのかを表す値型。
//!
//! `保管先基底パス`（domain層）は`/`区切りの綴りだけを知る値型であり、生の文字列アクセサを
//! 持たない。基点が実在するかどうかの確認にはファイルシステム上の実体が要るため、同じ基点を
//! ローカルのパスとして表すこの型を別に持つ。

use std::path::{Path, PathBuf};

use lfs_rclone_domain::保管エラー;

/// ローカルファイルシステム上の保管先の基点。マウント済みのドライブの中を指す想定である。
#[derive(Debug, Clone, PartialEq, Eq)]
#[repr(transparent)]
pub struct ローカル保管先ルートディレクトリ(PathBuf);

impl ローカル保管先ルートディレクトリ {
    pub fn 生成する(ルート: impl Into<PathBuf>) -> Self {
        Self(ルート.into())
    }

    /// ファイルシステムAPIへ渡すための参照（境界1箇所）。
    pub fn パス(&self) -> &Path {
        &self.0
    }

    /// 基点が実在するディレクトリであることを確かめる。
    ///
    /// 注意: 基点が無いときに中間ディレクトリの作成で基点ごと作ってしまうと、ドライブが
    /// マウントされていない状態でも書き込みが成功したように見え、実体がローカルディスクへ
    /// 溜まる。よってここでは作成せず、設定不備として明示的に失敗させる。説明文には
    /// PC固有の絶対パスを載せない（CLAUDE.md「認証情報を混入させない」）。
    pub fn 実在を確かめる(&self) -> Result<(), 保管エラー> {
        if self.0.is_dir() {
            Ok(())
        } else {
            Err(保管エラー::設定不備 {
                説明: "保管先のルートディレクトリが存在しません。PC設定のbase_pathと、ドライブがマウントされているかを確認してください"
                    .to_owned(),
            })
        }
    }
}
