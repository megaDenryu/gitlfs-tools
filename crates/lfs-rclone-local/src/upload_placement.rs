//! アップロードの配置手続き。保管先の一時パスへ複製してから最終パスへ移す。
//!
//! 保管先で直接最終パスへ書かないのは、書き込みの途中で中断したときに、内容が欠けた実体が
//! 最終パスへ残るのを避けるためである（rcloneの実装が`copyto`と`moveto`の2段で行うのと
//! 同じ理由）。移動は同じ基点の中で行うため、ファイルシステムをまたがない。

use std::path::Path;

use lfs_rclone_domain::保管エラー;

use crate::local_object_file_path::保管先オブジェクトのローカルファイルパス;

/// 1回のアップロードで使う一時パスと最終パスの組。両方をこの型が所有し、片づけまでを
/// この型のメソッドで完結させる。
pub(crate) struct 一時パス経由の配置 {
    一時パス: 保管先オブジェクトのローカルファイルパス,
    最終パス: 保管先オブジェクトのローカルファイルパス,
}

impl 一時パス経由の配置 {
    pub(crate) fn 生成する(
        一時パス: 保管先オブジェクトのローカルファイルパス,
        最終パス: 保管先オブジェクトのローカルファイルパス,
    ) -> Self {
        Self { 一時パス, 最終パス }
    }

    /// 検証済みのローカル入力を最終パスへ置く。途中で失敗した場合は保管先の一時パスを
    /// 片づけてから失敗を返す（片づけ自体の失敗は元の失敗を覆い隠さないよう無視する）。
    pub(crate) fn ローカル入力を最終パスへ置く(&self, 転送元: &Path) -> Result<(), 保管エラー> {
        let 配置結果 = self.一時パスへ複製してから最終パスへ移す(転送元);
        if 配置結果.is_err() {
            let _ = self.一時パス.実体を削除する();
        }
        配置結果
    }

    fn 一時パスへ複製してから最終パスへ移す(&self, 転送元: &Path) -> Result<(), 保管エラー> {
        self.一時パス.中間ディレクトリを用意する()?;
        std::fs::copy(転送元, self.一時パス.パス()).map_err(|エラー| 保管エラー::ローカル入出力 {
            説明: format!("保管先の一時パスへの複製に失敗しました: {エラー}"),
        })?;

        self.最終パス.中間ディレクトリを用意する()?;
        std::fs::rename(self.一時パス.パス(), self.最終パス.パス()).map_err(|エラー| 保管エラー::ローカル入出力 {
            説明: format!("保管先の一時パスから最終パスへの移動に失敗しました: {エラー}"),
        })
    }
}
