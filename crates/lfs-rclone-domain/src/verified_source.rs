//! バイト数とSHA-256を検証し終えたローカル入力を表す値型。

use std::path::Path;

use crate::expected_byte_count::期待バイト数;
use crate::object_identifier::オブジェクト識別子;
use crate::storage_error::{保管エラー, 整合性エラー};
use crate::unverified_local_file::{ローカルファイル計測結果, 検証前のローカルファイル};

/// バイト数とSHA-256をオブジェクト識別子と照合し終えたローカル入力。
///
/// 注意: 生成は`検証前のローカルファイル::検証する`経由に限る。フィールドを公開せず、
/// 実測を経ない値がこの型として組み立てられないようにする（判断5「検証済みであることを
/// 型で表す」）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 検証済み転送元 {
    識別子: オブジェクト識別子,
    バイト数: 期待バイト数,
    入力ファイル: 検証前のローカルファイル,
}

impl 検証済み転送元 {
    pub(crate) fn 生成する(
        識別子: &オブジェクト識別子,
        期待バイト数: 期待バイト数,
        入力ファイル: 検証前のローカルファイル,
        計測結果: ローカルファイル計測結果,
    ) -> Result<Self, 保管エラー> {
        if 計測結果.バイト数 != 期待バイト数 {
            return Err(保管エラー::整合性(整合性エラー::バイト数の不一致 {
                期待: 期待バイト数,
                実際: 計測結果.バイト数,
            }));
        }

        if 計測結果.内容ハッシュ != *識別子 {
            return Err(保管エラー::整合性(整合性エラー::内容ハッシュの不一致 {
                期待: 識別子.clone(),
                実際: 計測結果.内容ハッシュ,
            }));
        }

        Ok(Self {
            識別子: 識別子.clone(),
            バイト数: 期待バイト数,
            入力ファイル,
        })
    }

    pub fn 識別子(&self) -> &オブジェクト識別子 {
        &self.識別子
    }

    pub fn バイト数(&self) -> 期待バイト数 {
        self.バイト数
    }

    /// rcloneへ渡す等、外部境界での使用のための参照。
    pub fn パス(&self) -> &Path {
        self.入力ファイル.パス()
    }
}
