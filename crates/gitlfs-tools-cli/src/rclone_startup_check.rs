//! `init`の起動確認2種（rclone実行ファイルの起動可否確認、rcloneの実行そのものの疎通確認）。
//! `Rclone初期化境界::開始する`の一手続きとして呼ばれる私有ヘルパー
//! （グローバルCLAUDE.md「サービスの依存保持とコールバックの限定」条1: 親のサービス型
//! `Rclone初期化境界`が依存を保持した上での工程ヘルパー）。

use std::io;
use std::process::{Command, Stdio};

use gitlfs_tools_domain::{オブジェクト識別子, 保管エラー, 期待バイト数, Rclone実行ファイルの場所};
use gitlfs_tools_protocol::初期化エラー;
use gitlfs_tools_rclone::Rclone保管庫;
use gitlfs_tools_storage_port::オブジェクト保管庫;

const 識別子の文字数: usize = 64;
const 起動確認用引数: &str = "version";

/// rclone実行ファイルが実際に起動できるかを確かめる。PC設定`rclone_executable`が明示した
/// パスとPATH解決のどちらであっても、`Rclone実行ファイルの場所::プログラム名`が返す同じ
/// プログラム名で副作用の無い`version`引数を渡し、子プロセスを起動できるかどうかだけを見る
/// （終了コード・標準出力の内容は見ない）。子プロセスの標準出力・標準エラー出力は捕捉し、
/// agentの標準出力（Git LFSとの通信専用）へは流さない。起動できなければ、明示パスか
/// PATH解決かで利用者が取るべき対処が違うため、それぞれに合ったメッセージを添えて
/// `初期化エラー::Rclone実行ファイル不在`を返す。
pub(crate) fn rclone実行ファイルの起動可否を確かめる(場所: &Rclone実行ファイルの場所) -> Result<(), 初期化エラー> {
    起動を試みる(場所).map_err(|エラー| 初期化エラー::Rclone実行ファイル不在 { 説明: 起動失敗の説明を作る(場所, &エラー) })
}

fn 起動を試みる(場所: &Rclone実行ファイルの場所) -> Result<(), io::Error> {
    Command::new(場所.プログラム名()).arg(起動確認用引数).stdin(Stdio::null()).output().map(|_| ())
}

fn 起動失敗の説明を作る(場所: &Rclone実行ファイルの場所, エラー: &io::Error) -> String {
    match 場所 {
        Rclone実行ファイルの場所::明示された場所(_) => format!(
            "PC設定のrclone_executableが指す実行ファイルを起動できませんでした: {エラー}。PC設定のパスを確認してください。"
        ),
        Rclone実行ファイルの場所::PATH上の実行ファイル => format!(
            "rcloneをPATH上で起動できませんでした: {エラー}。\
             rcloneを導入するか、PC設定のrclone_executableで実行ファイルのパスを明示してください。"
        ),
    }
}

/// ダミーの識別子で`存在を確認する`を1回呼び、rcloneがリモートへ問い合わせられることを
/// 確かめる。対象の識別子が存在するかどうかは問わない（未存在も正常応答として扱う）。
///
/// 注意: ここに到達した時点で`rclone実行ファイルの起動可否を確かめる`により、rclone自体の
/// 起動可否は明示パス・PATH解決のどちらでも確認済みである。この問い合わせが失敗する原因として
/// 残るのはリモートの設定・認証・接続であるため、`存在を確認する`が返す`保管エラー`の
/// 種別によらず`保管エラー::認証接続`へ写像する（README.mdのエラーコード10対応表と
/// 一致させる）。転送中（`upload`/`download`）の子プロセス失敗は、原因を認証へ
/// 絞り込めないため、この写像を行わず従来どおり`保管エラー::子プロセス`のまま扱う。
pub(crate) fn rcloneの起動を確認する(保管庫: &Rclone保管庫) -> Result<(), 保管エラー> {
    let 識別子 = オブジェクト識別子::生成する(&"0".repeat(識別子の文字数))?;
    保管庫.存在を確認する(&識別子, 期待バイト数::生成する(0)).map_err(|エラー| 保管エラー::認証接続 {
        説明: format!("rcloneの起動確認でリモートへの問い合わせに失敗しました: {エラー}"),
    })?;
    Ok(())
}
