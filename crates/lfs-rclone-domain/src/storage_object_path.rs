//! 保管先の1オブジェクトを指すパスを表す値型。

/// 保管先（rcloneのリモート）における1オブジェクトへのパス。区切りは常に`/`とする
/// （保管先はWindowsのファイルシステムではない）。
///
/// 注意: 生成は`保管先基底パス`のメソッド経由に限る。任意の文字列から組み立てられる
/// 公開コンストラクタを持たない。パスの綴りは`保管先基底パス`という1箇所へ閉じる。
#[derive(Debug, Clone, PartialEq, Eq)]
#[repr(transparent)]
pub struct 保管先オブジェクトパス(String);

impl 保管先オブジェクトパス {
    pub(crate) fn 生成する(パス文字列: String) -> Self {
        Self(パス文字列)
    }

    /// rcloneコマンド引数等、外部境界へ渡すための文字列表現。
    pub fn 文字列表現(&self) -> &str {
        &self.0
    }
}
